/* MSX-MUSIC: the YM2413 (OPLL) of every MSX2+, at I/O ports 7Ch (register) and 7Dh (data), on emu2413 v1.5.9 (MIT,
 * Mitsutaka Okazaki; vendored unmodified in emu2413/, licences/emu2413.md). Its source is included here so that this file
 * can name the chip's wave tables for the quick state. MIT, Retro-Recomp.
 *
 * The chip runs from the 3.58 MHz clock: one sample every 72 machine cycles (49,716 Hz, emu2413's own rate, so no rate
 * converter), held between samples; msx_psg.c adds it to the mix at each of its ticks. Ports 7Ch-7Dh are write-only.
 *
 * Quick state: the chip field by field (msx_opll_state.inc, generated by retrorecomp/nes_state_layout.py from emu2413.h; the
 * test tests/test_msx_music.py holds it to a fresh generation), then each slot's patch and wave table as an index, as the
 * NES's VRC7 does; the address latch, the next sample's cycle and the held output. */
#include "emu2413/emu2413.c"
#include "msx_music.h"
#include "state_io.h"
#include "msx_opll_state.inc"

enum { MSX_MUSIC_CLOCK = 3579545, MSX_MUSIC_RATE = 49716, MSX_MUSIC_CYCLES = 72 };

typedef struct {
    OPLL *opll;
    uint8_t latch;
    uint64_t next;        /* the machine cycle of the next chip sample */
    int16_t out;          /* the last sample, held until the next */
} MsxMusic;

static MsxMusic music;
static MsxFm hooks;

static void music_write(void *chip, uint8_t port, uint8_t value)
{
    MsxMusic *c = (MsxMusic *)chip;
    if (port == 0x7C)
        c->latch = value;
    else
        OPLL_writeReg(c->opll, c->latch, value);
}

static int music_sample(void *chip, uint64_t cycle)
{
    MsxMusic *c = (MsxMusic *)chip;
    while (c->next <= cycle) {
        c->out = OPLL_calc(c->opll);
        c->next += MSX_MUSIC_CYCLES;
    }
    return c->out;
}

static void music_reset(void *chip, uint64_t cycle)
{
    MsxMusic *c = (MsxMusic *)chip;
    OPLL_reset(c->opll);
    c->latch = 0;
    c->next = cycle + MSX_MUSIC_CYCLES;
    c->out = 0;
}

/* The OPLL's image: its fields, then each slot's patch index and wave-table index (18 + 18 bytes). */
static size_t image_size(void) { return rr_size_OPLL() + 36; }

static void music_state(void *chip, void *raw)
{
    MsxMusic *c = (MsxMusic *)chip;
    RetroStateIO *io = (RetroStateIO *)raw;
    uint8_t image[4096];
    size_t size = image_size();
    if (size > sizeof image) { io->ok = false; return; }
    if (io->mode == RR_STATE_WRITE) {
        uint8_t *cursor = rr_ser_OPLL(image, c->opll);
        for (int i = 0; i < 18; ++i) *cursor++ = (uint8_t)(c->opll->slot[i].patch - c->opll->patch);
        for (int i = 0; i < 18; ++i) *cursor++ = (uint8_t)(c->opll->slot[i].wave_table == wave_table_map[1]);
    } else {
        /* Checked before it is applied, on a copy: rr_state_bytes copies nothing out in the check pass. */
        if (!io->ok || io->pos > io->size || size > io->size - io->pos) { io->ok = false; return; }
        memcpy(image, io->data + io->pos, size);
    }
    rr_state_bytes(io, image, size);
    uint8_t latch = c->latch;
    uint64_t next = c->next;
    int64_t out = c->out;
    latch = (uint8_t)rr_state_word(io, latch, 1, 0xFF);
    next = rr_state_word(io, next, 8, UINT64_MAX);
    if (io->mode == RR_STATE_WRITE) {
        rr_state_word(io, (uint64_t)(uint16_t)c->out, 2, 0xFFFF);
        return;
    }
    out = (int16_t)rr_state_word(io, 0, 2, 0xFFFF);
    if (!io->ok)
        return;
    OPLL chip_image;
    memset(&chip_image, 0, sizeof chip_image);
    const uint8_t *cursor = rr_de_OPLL(image, &chip_image);
    if (chip_image.clk != c->opll->clk || chip_image.rate != c->opll->rate) { io->ok = false; return; }
    for (int i = 0; i < 18; ++i)
        if (cursor[i] >= 19 * 2 || cursor[18 + i] > 1) { io->ok = false; return; }
    if (io->mode != RR_STATE_APPLY)
        return;
    rr_de_OPLL(image, c->opll);
    for (int i = 0; i < 18; ++i) {
        c->opll->slot[i].patch = &c->opll->patch[cursor[i]];
        c->opll->slot[i].wave_table = wave_table_map[cursor[18 + i] & 1];
    }
    c->latch = latch;
    c->next = next;
    c->out = (int16_t)out;
}

MsxFm *msx_music_create(void)
{
    if (!music.opll) {
        music.opll = OPLL_new(MSX_MUSIC_CLOCK, MSX_MUSIC_RATE);
        if (!music.opll || music.opll->conv)
            return NULL;
        OPLL_setChipType(music.opll, OPLL_2413_TONE);
    }
    music_reset(&music, 0);
    hooks.chip = &music;
    hooks.write = music_write;
    hooks.sample = music_sample;
    hooks.state = music_state;
    hooks.reset = music_reset;
    return &hooks;
}
