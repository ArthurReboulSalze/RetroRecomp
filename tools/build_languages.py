"""Regenerate the small UTF-8 game catalogue and glyphs from reviewed locales.

Requires Pillow/fontTools and Noto Sans CJK / Noto Sans Mono source fonts.
Only derived subsets and menu glyphs are shipped, never the complete fonts.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from smsrecomp.languages import GAME_LANGUAGES, LANGUAGES, LANGUAGE_NAMES


def cstr(text):
    return '"' + ''.join(chr(b) if 32 <= b < 127 and chr(b) not in '\\"' else '\\%03o'%b for b in text.encode('utf-8')) + '"'


def formats(text):
    return re.findall(r'%(?!%)[-+ #0]*\d*(?:\.\d+)?(?:ll|[hlz])?[diuoxXfFeEgGcs]', text)


def catalogue():
    data = {code:json.loads((ROOT/'assets/locales'/f'{code}.json').read_text(encoding='utf-8')) for code in LANGUAGES[1:]}
    keys = sorted(data['fr']['runtime'])
    for code, value in data.items():
        assert set(value['runtime']) == set(keys), code
        for key in keys:
            assert formats(value['runtime'][key]) == formats(key), (code, key)
    # Every locale stays complete; generated games carry the Latin-script ones.
    count = len(GAME_LANGUAGES)
    rows = []
    for key in keys:
        rows.append('    {' + ','.join(cstr(s) for s in [key]+[data[code]['runtime'][key] for code in GAME_LANGUAGES[1:]])+'},')
    text = '/* Generated by tools/build_languages.py; edit assets/locales instead. */\n'
    text += f'static const char *const rr_language_codes[{count}] = {{'+','.join(cstr(s) for s in GAME_LANGUAGES)+'};\n'
    text += f'static const char *const rr_language_names[{count}] = {{'+','.join(cstr(s) for s in LANGUAGE_NAMES[:count])+'};\n'
    text += f'static const char *const rr_translations[][{count}] = {{\n'+'\n'.join(rows)+'\n};\n'
    (ROOT/'native/runtime_catalog.inc').write_bytes(text.encode('ascii'))
    return data


def game_characters(data):
    # Non-ASCII characters a generated game can draw.
    runtime = ''.join(LANGUAGE_NAMES[:len(GAME_LANGUAGES)])
    runtime += ''.join(k+''.join(data[code]['runtime'][k] for code in GAME_LANGUAGES[1:]) for k in data['fr']['runtime'])
    return sorted(set(c for c in runtime if ord(c)>=127))


def glyph_source(entries, pixels):
    text = '/* Noto-derived menu glyphs, SIL OFL 1.1; see licenses/Noto.md. */\n'
    text += 'static const struct RR_Glyph { uint32_t code, offset; unsigned width; } rr_glyphs[] = {\n'
    text += '\n'.join('    {%d,%d,%d},'%e for e in entries)+'\n};\n'
    text += 'static const unsigned char rr_glyph_pixels[] = {\n'
    text += '\n'.join('    '+','.join(str(x) for x in pixels[i:i+24])+',' for i in range(0,len(pixels),24))+'\n};\n'
    return text


def prune_glyphs(data):
    # Without the source fonts, keep only the baked glyphs games still draw.
    path = ROOT/'native/runtime_glyphs.inc'
    source = path.read_text(encoding='ascii')
    entries = [tuple(map(int, e)) for e in re.findall(r'\{(\d+),(\d+),(\d+)\},', source)]
    blob = bytes(int(x) for x in re.findall(r'\d+', source.split('rr_glyph_pixels[] = {', 1)[1]))
    needed = {ord(c) for c in game_characters(data)}
    missing = needed - {code for code, _, _ in entries}
    assert not missing, ('these glyphs need the source fonts', sorted(missing))
    kept, pixels = [], bytearray()
    for code, offset, width in entries:
        if code in needed:
            kept.append((code, len(pixels), width))
            pixels.extend(blob[offset:offset+12*width])
    path.write_bytes(glyph_source(kept, pixels).encode('ascii'))
    return len(kept), len(pixels)


def fonts(data, cjk, mono, *, runtime_only=False):
    from PIL import Image, ImageDraw, ImageFont
    from fontTools import subset
    from fontTools.ttLib import TTFont
    characters = game_characters(data)
    mono_face = ImageFont.truetype(str(mono),10)
    cjk_face = ImageFont.truetype(str(cjk),12,index=0)
    mono_map = TTFont(mono).getBestCmap()
    cjk_map = TTFont(cjk,fontNumber=0).getBestCmap()
    entries, pixels = [], bytearray()
    for char in characters:
        wide = ord(char)>=0x2e80
        face = cjk_face if wide else mono_face
        assert ord(char) in (cjk_map if wide else mono_map), repr(char)
        width = 12 if wide else 6
        image = Image.new('L',(width,12))
        draw = ImageDraw.Draw(image)
        draw.text((0,10),char,font=face,fill=255,anchor='ls',stroke_width=0)
        assert image.getbbox(), repr(char)
        # Keep the original Latin accents. CJK/Cyrillic were visibly too large
        # beside the six-pixel ASCII font: reduce both axes by a third, while
        # keeping the existing twelve-pixel line height and vertical alignment.
        if wide or 0x0400 <= ord(char) <= 0x052f:
            width = width * 2 // 3
            reduced = image.resize((width,8),Image.Resampling.LANCZOS)
            image = Image.new('L',(width,12))
            image.paste(reduced,(0,2))
        entries.append((ord(char),len(pixels),width))
        pixels.extend(image.tobytes())
    (ROOT/'native/runtime_glyphs.inc').write_bytes(glyph_source(entries, pixels).encode('ascii'))

    if runtime_only:
        return len(entries),len(pixels)

    ui_fonts(data,cjk)
    return len(entries),len(pixels)


def ui_fonts(data,cjk):
    """Update converter text without changing any generated-game glyphs."""
    from fontTools import subset
    from fontTools.ttLib import TTFont
    ui = ''.join(LANGUAGE_NAMES) + ''.join(json.dumps(v,ensure_ascii=False) for v in data.values())
    from smsrecomp.i18n import STRINGS
    ui += ''.join(''.join(pair) for pair in STRINGS.values())
    points = set(range(32,127)) | {ord(c) for c in ui if ord(c)>=32}
    font_hashes = {}
    for index,label in ((0,'JP'),(2,'SC')):
        font = TTFont(cjk,fontNumber=index)
        assert points <= set(font.getBestCmap()), sorted(points-set(font.getBestCmap()))
        options = subset.Options()
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=points)
        sub.subset(font)
        family = 'RetroRecomp UI '+label
        # OFL reserved family name is not retained by the modified subset.
        names = {1:family,2:'Regular',3:family+' Regular',4:family+' Regular',6:'RetroRecompUI'+label+'-Regular',16:family,17:'Regular'}
        font['name'].names = [n for n in font['name'].names if n.nameID not in names]
        for nameid,name in names.items():
            font['name'].setName(name,nameid,3,1,0x409)
        path = ROOT/'assets'/('RetroRecomp-UI-'+label+'.otf')
        font.save(path)
        font_hashes[label]=hashlib.sha256(path.read_bytes()).hexdigest()
    (ROOT/'assets/font-coverage.json').write_text(json.dumps({'font_sha256':font_hashes,'codepoints':sorted(points)},indent=2)+'\n',encoding='ascii')
    return font_hashes


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cjk',type=Path)
    parser.add_argument('--mono',type=Path)
    parser.add_argument('--runtime-only',action='store_true',
                        help='Regenerate game glyphs without changing converter font subsets')
    parser.add_argument('--ui-only',action='store_true',
                        help='Regenerate only converter fonts, preserving all game glyphs')
    args = parser.parse_args()
    if args.ui_only:
        if not args.cjk or args.runtime_only:
            parser.error('--ui-only requires --cjk and cannot be combined with --runtime-only')
        data={code:json.loads((ROOT/'assets/locales'/f'{code}.json').read_text(encoding='utf-8'))
              for code in LANGUAGES[1:]}
        print(json.dumps(ui_fonts(data,args.cjk)))
        return
    data = catalogue()
    if args.cjk and args.mono:
        count,size = fonts(data,args.cjk,args.mono,runtime_only=args.runtime_only)
        print(f'{count} extended glyphs: {size} alpha bytes')
    elif args.cjk or args.mono or args.runtime_only:
        parser.error('both source fonts are required')
    else:
        count, size = prune_glyphs(data)
        print(f'{count} baked glyphs kept: {size} alpha bytes')


if __name__ == '__main__':
    main()
