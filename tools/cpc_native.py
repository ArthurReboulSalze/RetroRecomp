"""The Amstrad CPC natively: authored programs translated by the banked Z80 chain, run headless and compared with the reference.

    python -B tools/cpc_native.py [--json PATH]

For each program of tools/cpc_reference.py (timing, interrupts and picture, a sector read as AMSDOS reads it) taken as the
system ROM: its bodies are generated by the CPC's own generator (retrorecomp/cpc_build.generate, the chain's emitter with
the CPC's costs and 16-bit ports), the project builds `cpc_check` (the bodies, the step loop and native/cpc_machine/cpc_glue.inc)
and `cpc_reference` (the reference interpreter on the same board) from the same sources, both run with the same options, and
every field of their JSON must be equal (the CPU, the time, the interrupts, the RAM, the picture, the Gate Array, the AY, the
controller, the watched bytes), the native run adding its native and fallback step counts. And code built in RAM byte by byte
(tools/cpc_reference.ram_program): interpreted and counted on the first generation, learned (--learn), native with byte guards
on the second (native.patterns), equal to the reference both times. No firmware, no game.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'tools'))

import cpc_reference  # noqa: E402

WORK = ROOT / '.build' / 'cpc-native'
NATIVE_ONLY = ('native_steps', 'fallback_steps')
REFERENCE_ONLY = ('steps',)
AMSDOS_STANDIN = b'\xC9' * 0x4000               # a 16 KiB stand-in: never paged in by these programs


def project(work: Path) -> None:
    from retrorecomp import cpc_build
    machine = ' '.join((*cpc_build.MACHINE_SOURCES, *cpc_build.DISK_SOURCES, *cpc_build.SHARED_SOURCES))
    (work / 'CMakeLists.txt').write_text(f'''cmake_minimum_required(VERSION 3.20)
project(RetroCpc LANGUAGES C)
set(CMAKE_C_STANDARD 11)
set(CMAKE_MSVC_RUNTIME_LIBRARY "MultiThreaded$<$<CONFIG:Debug>:Debug>")
add_executable(cpc_reference cpc_reference_main.c {machine} runtime_reference.c)
file(GLOB bodies "generated/game_banked_ops_*.c")
add_library(cpc_bodies OBJECT generated/game_banked_index.c ${{bodies}})
target_include_directories(cpc_bodies PRIVATE "${{CMAKE_CURRENT_SOURCE_DIR}}" "${{CMAKE_CURRENT_SOURCE_DIR}}/generated")
target_compile_definitions(cpc_bodies PRIVATE SMSRECOMP_BANKED_AOT)
add_executable(cpc_check cpc_native_main.c {machine} runtime_reference.c $<TARGET_OBJECTS:cpc_bodies>)
foreach(target cpc_reference cpc_check)
  target_include_directories(${{target}} PRIVATE "${{CMAKE_CURRENT_SOURCE_DIR}}" "${{CMAKE_CURRENT_SOURCE_DIR}}/generated")
  target_compile_definitions(${{target}} PRIVATE SMSRECOMP_BANKED_AOT _CRT_SECURE_NO_WARNINGS)
  if(NOT WIN32)
    target_link_libraries(${{target}} PRIVATE m)
  endif()
endforeach()
''', encoding='utf-8', newline='\n')


def build(work: Path, rom: bytes) -> tuple[Path, Path]:
    from retrorecomp import cpc_build, toolchain
    from retrorecomp.platforms import build_executable, build_jobs, cmake_target_args
    work.mkdir(parents=True, exist_ok=True)
    cpc_build.generate(work, rom, AMSDOS_STANDIN)
    cpc_build.stage_sources(work)
    for name in ('cpc_native_main.c', 'cpc_reference_main.c'):
        shutil.copyfile(ROOT / 'native' / 'cpc_machine' / name, work / name)
    project(work)
    selection = toolchain.select()
    flags = subprocess.CREATE_NO_WINDOW if os.name == 'nt' else 0
    for step in ([str(selection.cmake), '-S', str(work), '-B', str(work / 'build'), '-G', selection.generator,
                  '-DCMAKE_BUILD_TYPE=Release', *cmake_target_args()],
                 [str(selection.cmake), '--build', str(work / 'build'), '--config', 'Release', '--parallel', build_jobs()]):
        result = subprocess.run(step, capture_output=True, text=True, creationflags=flags)
        if result.returncode:
            raise RuntimeError(result.stdout[-6000:] + result.stderr[-2000:])
    return build_executable(work / 'build', 'cpc_check'), build_executable(work / 'build', 'cpc_reference')


def run(exe: Path, work: Path, rom: bytes, args: list[str]) -> dict:
    image = work / 'system.rom'
    image.write_bytes(rom)
    flags = subprocess.CREATE_NO_WINDOW if os.name == 'nt' else 0
    out = subprocess.run([str(exe), '--system', str(image), *args], capture_output=True, text=True, timeout=600,
                         creationflags=flags, cwd=work)
    if out.returncode:
        raise RuntimeError(f'{exe.name}: {out.stderr[-2000:]}')
    return json.loads(out.stdout.strip().splitlines()[-1])


def compare(native: dict, reference: dict) -> dict:
    """The fields that differ (native, reference), the step counts of each side left out."""
    keys = (set(native) | set(reference)) - set(NATIVE_ONLY) - set(REFERENCE_ONLY)
    return {key: (native.get(key), reference.get(key)) for key in sorted(keys) if native.get(key) != reference.get(key)}


def cases() -> list[tuple[str, bytes, list[str]]]:
    disk = WORK / 'disk.dsk'
    disk.parent.mkdir(parents=True, exist_ok=True)
    disk.write_bytes(cpc_reference.disk_image())
    watches = [part for n in (0, 1, 255, 511) for part in ('--watch', f'{0x4000 + n:04X}')]
    watches += [part for n in range(7) for part in ('--watch', f'{0x4200 + n:04X}')]
    return [
        ('timing', cpc_reference.timing_program(), ['--frames', '5', '--until-halt']),
        ('interrupts', cpc_reference.interrupt_program(), ['--frames', '100', '--watch', '8000', '--watch', '8001']),
        ('disk', cpc_reference.disk_program(), ['--disk', str(disk), '--frames', '5', '--until-halt', *watches]),
    ]


def learning() -> dict:
    """The routine built in RAM and called 200 times: the first generation runs it on the counted fallback and learns it
    (--learn); the second translates it with byte guards (native.patterns): equal to the reference both times."""
    work = WORK / 'ram'
    rom = cpc_reference.ram_program()
    args = ['--frames', '5', '--until-halt', '--watch', '8002']
    patterns = work / 'native.patterns'
    patterns.unlink(missing_ok=True)
    passes = []
    for _ in range(2):
        native_exe, reference_exe = build(work, rom)
        learned = work / 'learned.txt'
        learned.unlink(missing_ok=True)
        native = run(native_exe, work, rom, [*args, '--learn', str(learned)])
        reference = run(reference_exe, work, rom, args)
        passes.append({'fallback_steps': native['fallback_steps'], 'native_steps': native['native_steps'],
                       'differences': compare(native, reference),
                       'counted': native['watch']['8002']})
        words = learned.read_text(encoding='utf-8').split() if learned.is_file() else []
        if not words:
            break
        patterns.write_text(''.join(word + '\n' for word in sorted(set(words))), encoding='utf-8', newline='\n')
    return {'passes': passes,
            'equal': all(not p['differences'] for p in passes) and all(p['counted'] == 200 * 3 % 256 for p in passes),
            'learned': passes[0]['fallback_steps'] > 0 and len(passes) == 2 and passes[1]['fallback_steps'] == 0}


def checks() -> dict:
    results = {}
    ram = learning()
    results['ram'] = {'equal': ram['equal'] and ram['learned'], 'differences': [p['differences'] for p in ram['passes']],
                      'native_steps': [p['native_steps'] for p in ram['passes']],
                      'fallback_steps': [p['fallback_steps'] for p in ram['passes']], 'frames': None, 'cycles': None}
    for name, rom, args in cases():
        work = WORK / name
        native_exe, reference_exe = build(work, rom)
        native = run(native_exe, work, rom, args)
        reference = run(reference_exe, work, rom, args)
        differences = compare(native, reference)
        results[name] = {'equal': not differences, 'differences': differences, 'native_steps': native['native_steps'],
                         'fallback_steps': native['fallback_steps'], 'frames': native['frames'], 'cycles': native['cycles']}
    return results


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--json', type=Path)
    args = parser.parse_args()
    results = checks()
    for name, result in results.items():
        print(('ok   ' if result['equal'] else 'FAIL ') + f"{name}: native {result['native_steps']} steps, fallback "
              f"{result['fallback_steps']}" + ('' if result['equal'] else f", differs: {result['differences']}"))
    if args.json:
        args.json.write_text(json.dumps(results, indent=1) + '\n', encoding='utf-8')
    return 0 if all(result['equal'] for result in results.values()) else 1


if __name__ == '__main__':
    raise SystemExit(main())
