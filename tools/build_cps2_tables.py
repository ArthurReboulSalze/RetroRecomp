"""Write retrorecomp/cps2_tables.py: the substitution boxes and bit permutations of the CPS-2 opcode decryption, read from MAME's
src/mame/capcom/cps2crypt.cpp at the pinned revision (BSD-3-Clause, copyright-holders: Paul Leaman, Andreas Naive, Nicola Salmoria,
Charles MacDonald; the algorithm was broken by Andreas Naive, see the header of that file).

Development tool only. The tables are numbers about an algorithm, not game data and not a key. Reading them from the pinned source
(by hash) and generating the module keeps a transcription error out of the decryption; tests/test_cps2_crypt.py checks the module against
the source again and against MAME's decrypted opcodes where a romset is at hand.

    python -B tools/build_cps2_tables.py [--cache FOLDER] [--offline]
"""
import argparse
import hashlib
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from mame_driver_parse import MAME_REVISION, source_text, strip_comments  # noqa: E402

SOURCE = 'src/mame/capcom/cps2crypt.cpp'
OUTPUT = ROOT / 'retrorecomp' / 'cps2_tables.py'
PINNED = {SOURCE: 'c0f9ef55059fc48c5507a5f0ab1122826b44c98210adfe197e9b356d86a9a5e5'}


def numbers(text: str) -> list[int]:
    return [int(item) for item in re.findall(r'-?\d+', text)]


def groups(text: str, name: str) -> list[list[list[int]]]:
    """The sixteen boxes of one Feistel network as [table, inputs, outputs], round by round."""
    result = []
    for round_ in range(1, 5):
        block = re.search(r'const sbox ' + name + f'_r{round_}_boxes\\[4\\]\\s*=\\s*\\{{(.*?)\\n\\}};', text, re.S)
        if not block:
            raise SystemExit(f'{name} round {round_} not found.')
        inner = re.findall(r'\{([^{}]*)\}', block.group(1))
        if len(inner) != 12:
            raise SystemExit(f'{name} round {round_}: expected 12 groups, found {len(inner)}.')
        for box in range(4):
            table, inputs, outputs = (numbers(inner[3 * box + part]) for part in range(3))
            if len(table) != 64 or len(inputs) != 6 or len(outputs) != 2:
                raise SystemExit(f'{name} round {round_} box {box}: unexpected shape.')
            result.append([table, inputs, outputs])
    return result


def array(text: str, pattern: str, count: int) -> list[int]:
    match = re.search(pattern + r'\s*=\s*\{(.*?)\};', text, re.S)
    if not match:
        raise SystemExit('Missing array ' + pattern)
    values = numbers(match.group(1))
    if len(values) != count:
        raise SystemExit(f'{pattern}: expected {count} values, found {len(values)}.')
    return values


def build(cache: Path, offline: bool) -> str:
    raw = source_text(cache, SOURCE, PINNED[SOURCE], offline=offline)
    text = strip_comments(raw)
    out = ['"""The substitution boxes and bit permutations of the CPS-2 opcode decryption.', '',
           'Generated by tools/build_cps2_tables.py from MAME ' + SOURCE + ' at revision ' + MAME_REVISION + ',',
           'BSD-3-Clause, copyright-holders: Paul Leaman, Andreas Naive, Nicola Salmoria, Charles MacDonald (the algorithm was broken by',
           'Andreas Naive). Numbers about an algorithm: no game data and no key. Do not edit by hand.', '"""', '',
           f'SOURCE_SHA256 = {PINNED[SOURCE]!r}', '']
    for name in ('fn1', 'fn2'):
        out.append(f'{name.upper()}_GROUP_A = {array(text, "const int " + name + "_groupA\\[8\\]", 8)!r}')
        out.append(f'{name.upper()}_GROUP_B = {array(text, "const int " + name + "_groupB\\[8\\]", 8)!r}')
    out += ['', '# Per network: 16 boxes (4 rounds of 4) as (table of 64, input bit positions (-1: none), output bit positions)']
    for name in ('fn1', 'fn2'):
        out.append(f'{name.upper()}_BOXES = (')
        for table, inputs, outputs in groups(text, name):
            out.append(f'    ({tuple(table)!r}, {tuple(inputs)!r}, {tuple(outputs)!r}),')
        out.append(')')
    for label, function, count in (('EXPAND_FIRST_KEY', 'expand_1st_key', 96), ('EXPAND_SECOND_KEY', 'expand_2nd_key', 96),
                                   ('EXPAND_SUBKEY', 'expand_subkey', 64)):
        body = re.search(r'void ' + function + r'\([^)]*\)\s*\{(.*?)\n\}', text, re.S)
        values = array(body.group(1), r'static const int bits\[' + str(count) + r'\]', count)
        out.append(f'{label} = {tuple(values)!r}')
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', type=Path, default=ROOT / '.deps' / ('mame-cps1-' + MAME_REVISION[:7]))
    parser.add_argument('--output', type=Path, default=OUTPUT)
    parser.add_argument('--offline', action='store_true')
    args = parser.parse_args()
    data = build(args.cache, args.offline)
    args.output.write_text(data, encoding='ascii', newline='\n')
    print(f'{args.output}: {len(data)} bytes, sha256 {hashlib.sha256(data.encode()).hexdigest()}')


if __name__ == '__main__':
    main()
