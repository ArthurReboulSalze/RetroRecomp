"""Independent Z80 vectors replayed through the CPS-1 Z80 generator path (gate G10, independent CPU evidence).

    python -B tools/fetch_z80_vectors.py            (once: caches a sample of the pinned corpus in .deps/z80-vectors)
    python -B tools/cps1_z80_vector_selftest.py [--samples 32]

The corpus is SingleStepTests/z80 (MIT, generated by JSMoo, not recorded from hardware; synthetic instruction data, no
cartridge), a deterministic sample of every instruction family. The CPS-1 sound CPU is translated by the converter's own
`cps1_codegen.generate_z80` (one guarded body per distinct opcode form, operands read live) and dispatched by the patched
Geolith core (`cps1_build.z80_core(native=True)`). `native/cps1_z80_vector_checks.c` runs every vector on that path and
on the same core with every instruction interpreted, on a flat 64 KiB bus whose ports answer from the vector, and compares
registers (WZ and the alternate set included), written bytes, ports and the clock count with the vector, and the two paths
with each other. A vector whose code lies in the sound ROM windows or sound RAM runs as a native step; any other has no
native step on the board and must run interpreted and counted.

What it shows and what it does not: the behaviour of the translated bodies and of Geolith's Z80 against an oracle neither
was written from. P and Q (the undocumented flag-copy registers) are not compared: the core has neither. It says nothing
about the CPS-1 board, the YM2151 or OKI interrupts, hardware fidelity (the oracle is JSMoo) or gameplay.
"""
from __future__ import annotations
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from retrorecomp import cps1_build, cps1_codegen
from retrorecomp.core import run, toolchain
from retrorecomp.megadrive_z80 import opcode_key
from retrorecomp.neogeo_z80 import adapt_source
from retrorecomp.platforms import build_executable, build_jobs, cmake_target_args
from fetch_z80_vectors import fetch

FIELDS = 'pc sp a f b c d e h l i r ix iy wz af_ bc_ de_ hl_ im iff1 iff2'.split()
IMAGE_BYTES = 0x8000
SLOT = 4
NO_SLOT = 0xffffffff
# Geolith's Z80 differs from the oracle on a few behaviours the original core never modelled; both paths share them, so they are
# pinned (corpus revision, 32 vectors per family, Geolith pin) and any change, better or worse, fails until the page is updated:
# 899 of 51,328 vectors differ on state (flags 535, WZ 480, IM 38, IFF1 16, ports 128; a vector can differ on several), 128 on the clock.
BASELINE = {'corpus_revision': 'ebe1875d48f374bcfd4b505d8eb8ee751568b5f7', 'samples_per_family': 32, 'cases': 51328,
            'native_state': 50429, 'native_clock': 51200,
            'field_failures': {'f': 535, 'wz': 480, 'im': 38, 'iff1': 16, 'memory': 0, 'ports': 128}}


def window(case: dict) -> bytes:
    memory = dict(case['initial']['ram'])
    return bytes(memory.get((case['initial']['pc'] + n) & 0xffff, 0xA5) for n in range(4))


def prepare(cases: list[dict]):
    """(image, ram records, per-case slots): one image slot per distinct opcode form of the vectors that sit in code space."""
    keys, slots, ram = {}, [], {}
    for case in cases:
        pc, raw = case['initial']['pc'], window(case)
        key = opcode_key(raw)
        if key is None:
            slots.append(NO_SLOT)
        elif pc < 0xc000:
            if key not in keys:
                keys[key] = len(keys) * SLOT
            slots.append(keys[key])
        else:
            slots.append(NO_SLOT)
            if 0xd000 <= pc < 0xd800:
                ram[(pc, raw)] = {'address': pc, 'bytes': raw.hex()}
    assert len(keys) * SLOT <= IMAGE_BYTES, 'too many opcode forms for one image'
    image = bytearray(IMAGE_BYTES)
    for (mask, raw), offset in keys.items():
        image[offset:offset + 4] = raw
    return bytes(image), list(ram.values()), slots, len(keys)


def vectors_file(cases: list[dict], slots: list[int], path: Path) -> None:
    words = [len(cases)]
    for case, slot in zip(cases, slots):
        name = case['family'].encode('ascii').ljust(12, b'\0')
        words += [slot, len(case['cycles'])]
        words += list(struct.unpack('<3I', name))
        for phase in ('initial', 'final'):
            state = case[phase]
            words += [state[field] for field in FIELDS]
        for phase in ('initial', 'final'):
            words.append(len(case[phase]['ram']))
            for address, value in case[phase]['ram']:
                words += [address, value]
        ports = case.get('ports', [])
        words.append(len(ports))
        for address, value, direction in ports:
            words += [address, value, ord(direction)]
    path.write_bytes(struct.pack('<' + 'I' * len(words), *words))


def replay(samples: int = 32, project: Path | None = None) -> dict:
    project = project or ROOT / '.build' / 'cps1-z80-vector-selftest'
    project.mkdir(parents=True, exist_ok=True)
    source = fetch(samples)
    corpus = json.loads(source.read_text(encoding='utf-8'))
    cases = corpus['cases']
    image, ram, slots, forms = prepare(cases)
    cps1_build._engine(project, native=True)
    geolith, _ = cps1_build.sources()
    analysis = cps1_codegen.generate_z80(project, adapt_source((geolith / 'src/z80/z80.c').read_text(encoding='utf-8')), image, ram)
    vectors_file(cases, slots, project / 'vectors.bin')
    checks = (ROOT / 'native/cps1_z80_vector_checks.c').as_posix()
    (project / 'CMakeLists.txt').write_text(f'''cmake_minimum_required(VERSION 3.20)
project(RetroCps1Z80Vectors C)
set(CMAKE_C_STANDARD 11)
set(CMAKE_MSVC_RUNTIME_LIBRARY "MultiThreaded$<$<CONFIG:Debug>:Debug>")
add_executable(checks "{checks}" engine/z80/z80.c)
target_include_directories(checks PRIVATE . engine/z80)
if(MSVC)
  target_compile_options(checks PRIVATE /utf-8 /wd4996 /wd4244 /wd4267)
  target_compile_definitions(checks PRIVATE __BYTE_ORDER__=1234 __ORDER_LITTLE_ENDIAN__=1234)
endif()
''', encoding='utf-8')
    cmake, generator = toolchain()
    run([cmake, '-S', project, '-B', project / 'build', '-G', generator, *cmake_target_args()], log=project / 'build.log')
    run([cmake, '--build', project / 'build', '--config', 'Release', '--parallel', build_jobs()], log=project / 'build.log', timeout=1800)
    output = run([build_executable(project / 'build', 'checks'), project / 'vectors.bin'], timeout=900)
    result = json.loads(next(line for line in output.splitlines() if line.startswith('{')))
    result.update(corpus_revision=corpus['revision'], families_in_corpus=len(corpus['families']), samples_per_family=samples,
                  opcode_forms=forms, sound_ram_variants=len(ram), generated_native_bodies=analysis['structural_bodies'])
    (project / 'results.json').write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    return result


def summary(result: dict) -> str:
    totals, cases = result['totals'], result['cases']
    return (f"{cases} vectors ({result['families_in_corpus']} families, {result['samples_per_family']} each); "
            f"{result['rom_mapped']} in the sound ROM windows, {result['ram_mapped']} in sound RAM, {result['outside_code_map']} outside the code map; "
            f"state agrees with the vector: native {totals['native_state']}, reference {totals['reference_state']}; clocks: native "
            f"{totals['native_clock']}, reference {totals['reference_clock']}; the two paths agree: {totals['paths_equal']} (clocks {totals['paths_clock_equal']})")


def problems(result: dict) -> list[str]:
    """Required: the translated bodies equal the interpreted core on every vector (state and clock), every vector mapped to the
    sound ROM or RAM ran as a native step, and every other vector ran interpreted and counted."""
    found = []
    cases = result['cases']
    if result['native_as_expected'] != result['rom_mapped'] + result['ram_mapped']:
        found.append(f"{result['rom_mapped'] + result['ram_mapped'] - result['native_as_expected']} mapped vector(s) did not run as exactly one native step")
    if result['interpreted_and_counted_as_expected'] != result['outside_code_map']:
        found.append(f"{result['outside_code_map'] - result['interpreted_and_counted_as_expected']} unmapped vector(s) were not run interpreted and counted once")
    totals = result['totals']
    if totals['paths_equal'] != cases or totals['paths_clock_equal'] != cases:
        found.append(f"the native and interpreted paths differ on {cases - totals['paths_equal']} vector(s) of state and {cases - totals['paths_clock_equal']} of clock")
    if (result['corpus_revision'], result['samples_per_family'], cases) == (BASELINE['corpus_revision'], BASELINE['samples_per_family'],
                                                                         BASELINE['cases']):
        if totals['native_state'] != BASELINE['native_state'] or totals['native_clock'] != BASELINE['native_clock']                 or result['field_failures']['native'] != BASELINE['field_failures']:
            found.append('the differences with the vectors changed from the pinned baseline '
                         f"(state {totals['native_state']}, clock {totals['native_clock']}, fields {result['field_failures']['native']}); "
                         'review them, then update BASELINE and the CPU_Z80.md page')
    return found


def main(argv=None) -> int:
    samples = 32
    if argv and argv[:1] == ['--samples']:
        samples = int(argv[1])
    result = replay(samples)
    print(summary(result))
    failed = problems(result)
    for text in failed:
        print('PROBLEM', text)
    print(json.dumps(result))
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
