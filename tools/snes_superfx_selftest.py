"""Authored Super FX (GSU) checks against the real engine core, for NTSC and PAL builds.

The expected values come from tools/snes_superfx_model.py (written from the fullsnes
GSU chapter), never from superfx.c. This tool builds the case table, compiles
native/snes_superfx_checks.c against the staged engine sources like the other chip
checks, runs it and reports cases, assertions, mismatches and documented findings.
"""
from pathlib import Path
import argparse
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tools.snes_superfx_case import emit_case          # noqa: E402
from tools.snes_superfx_library import build_cases     # noqa: E402


def generate_header(cases=None):
    cases = cases if cases is not None else build_cases()
    declarations, rows = [], []
    positions = {id(case): serial for serial, case in enumerate(cases)}
    for serial, case in enumerate(cases):
        case.expect()
        base = positions[id(case.base)] if case.base is not None else -1
        text, row = emit_case(case, serial, base)
        declarations.append(text)
        rows.append(row)
    return ('/* Generated by tools/snes_superfx_selftest.py from tools/snes_superfx_model.py. */\n' +
            '\n'.join(declarations) + '\nstatic const RrGsuCase rr_gsu_cases[]={\n' +
            ',\n'.join(rows) + '\n};\n'), cases


def find_project(exe):
    for parent in exe.parents:
        if (parent / 'CMakeCache.txt').is_file():
            return parent, parent.parent
    raise RuntimeError('no CMake build folder above ' + str(exe))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--header-only', action='store_true')
    parser.add_argument('--standard', choices=('ntsc', 'pal'))
    args = parser.parse_args()
    work = ROOT / '.build/snes-superfx-selftest'
    work.mkdir(parents=True, exist_ok=True)
    header, cases = generate_header()
    (work / 'snes_superfx_cases.h').write_text(header, encoding='utf-8')
    summary = {'cases': len(cases)}
    if args.header_only:
        print(json.dumps(summary))
        return
    from retrorecomp.console16 import prepare16
    from retrorecomp.core import run, toolchain
    from tools.snes_scheduler_selftest import cartridge
    results = []
    for pal in (False, True):
        standard = 'pal' if pal else 'ntsc'
        if args.standard and args.standard != standard:
            continue
        path = work / (standard + '.sfc')
        data = cartridge(bytes.fromhex('40'), pal)
        data[0x7fc0:0x7fd5] = b'RR SUPERFX CHECKS'.ljust(21, b' ')
        path.write_bytes(data)
        exe = prepare16(path, 'snes', emit=lambda _: None)
        build, project = find_project(exe)
        (project / 'console16_main.c').write_text((ROOT / 'native/snes_superfx_checks.c').read_text(encoding='utf-8'),
                                                  encoding='utf-8')
        (project / 'snes_superfx_cases.h').write_text(header, encoding='utf-8')
        cmake, _ = toolchain()
        run([cmake, '--build', build, '--config', 'Release', '--parallel', '4'], log=work / (standard + '-build.log'))
        if not (work / 'project.json').exists() or not args.standard or args.standard == standard:
            (work / 'project.json').write_text(json.dumps(
                {'project': str(project), 'build': str(build), 'exe': str(exe)}) + '\n')
        output = run([exe], cwd=work, timeout=1800)
        lines = output.strip().splitlines()
        result = json.loads(lines[-1]) | {'standard': standard}
        result['detail'] = [line for line in lines[:-1] if line.startswith(('MISMATCH', 'FINDING'))]
        results.append(result)
    summary |= {'runs': results, 'passed': all(r['passed'] for r in results),
                'checks': sum(r['checks'] for r in results)}
    (work / 'results.json').write_text(json.dumps(summary, indent=2) + '\n')
    print(json.dumps({k: v for k, v in summary.items() if k != 'runs'} |
                     {'runs': [{k: v for k, v in r.items() if k != 'detail'} for r in results]}))
    for r in results:
        for line in r['detail'][:60]:
            print(r['standard'], line)


if __name__ == '__main__':
    main()
