"""Independent MC68000 vectors replayed through the CPS-1 generator path (gate G10, independent CPU evidence).

    python -B tools/cps1_vector_selftest.py [fixture ...]        (default: every fixture)

The vectors are the pinned SingleStepTests/m68000 fixtures of the repository (`tests/fixtures`, MIT, generated with
MAME, not recorded from hardware; synthetic instruction data, no cartridge). For each fixture a CPS-1 native project
is generated by the converter's own code: `cps1_build._engine` (the patched Musashi loop and the native dispatch),
`cps1_codegen.generate_m68k` (the static sweep and the translated steps) over a flat image that holds the vectors'
code. The harness `native/cps1_vector_checks.c` then runs every vector twice on a flat 24-bit bus (no board): through
the CPS-1 native steps and through the same Musashi with every instruction interpreted, and compares each path with
the vector's final registers, SR, PC, written bytes and clocks, and the two paths with each other.

What it shows and what it does not: CPU behaviour of the translated steps and of the Musashi reference against an
oracle that neither of them was written from. It does not show the CPS-1 board, hardware fidelity (the oracle is
MAME) or gameplay. The clocks of a CPS-1 game are Musashi's table with prefetch disabled, so the clock counts are
reported apart from the state counts and are not required to equal the vectors' bus-accurate timings.
"""
from __future__ import annotations
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from retrorecomp import cps1_build, cps1_codegen
from retrorecomp.core import run, toolchain
from retrorecomp.platforms import build_executable, build_jobs, cmake_target_args

FIXTURES = ('m68k-shifts', 'md-prefetch', 'md-exceptions')
REGS = [*(f'd{i}' for i in range(8)), *(f'a{i}' for i in range(7)), 'usp', 'ssp', 'sr', 'pc']
PROGRAM_BYTES = 0x400000
TRACE_GROUP = 'trace-delivery'    # the two authored vectors with the trace bit set: the CPS-1 Musashi is built without trace
# Groups where the Musashi reference (the CPS-1 conversions' fresh reference) differs from the MAME-made vectors while the
# translated steps follow them: DIV flags, CHK flags and clocks, one Line-F stack byte. Anything else is a failure.
REFERENCE_DEVIATIONS = frozenset(('DIVU-variable', 'DIVS-variable', 'CHK', 'CHK-phases', 'ILLEGAL_LINEF', 'ILLEGAL_LINEF-phases',
                                  'authored authored-variable'))


def state_literal(state: dict, pc_offset: int = 4) -> str:
    values = [state[key] if key != 'pc' else (state[key] - pc_offset) & 0xffffff for key in REGS]
    return '{' + ','.join(f'{v}u' for v in values) + '}'


def cases_header(fixture_name: str) -> tuple[str, bytes, dict]:
    """(C header text, program image, fixture) for one fixture; the code of every vector sits at its own address."""
    fixture = json.loads((ROOT / 'tests/fixtures' / fixture_name / 'cases.json').read_text(encoding='utf-8'))
    external = len(fixture['tests'])
    tests = list(fixture['tests'])
    if fixture_name == 'md-prefetch':
        tests += json.loads((ROOT / 'tests/fixtures/md-prefetch/authored.json').read_text(encoding='utf-8'))['tests']
    payload = bytearray(PROGRAM_BYTES)
    occupied, arrays, cases = {}, [], []
    for index, test in enumerate(tests):
        pc = test['initial']['pc'] - 4
        initial = dict(test['initial']['ram'])
        for address in range(pc, min(pc + 16, len(payload))):
            if address in initial:
                byte = initial[address]
                assert occupied.get(address, byte) == byte, 'Conflicting code fixtures'
                occupied[address] = payload[address] = byte
        for stage in ('initial', 'final'):
            pairs = test[stage]['ram']
            arrays.append(f'static const BytePair {stage}_{index}[] = {{' + ','.join(f'{{{a}u,{b}u}}' for a, b in pairs) + '};')
        cycles = test.get('length', test.get('cycles'))
        # A stopped STOP performs no new prefetch: the corpus final PC already is the following instruction.
        final_offset = 0 if test['group'] == 'STOP' and cycles == 4 else 4
        group = TRACE_GROUP if index >= external and 'post-instruction trace' in test['name'] else test['group']
        cases.append('{' + json.dumps(group + ': ' + test['name']) + ',' + state_literal(test['initial']) + ',' +
                     state_literal(test['final'], final_offset) + f',initial_{index},{len(test["initial"]["ram"])},'
                     f'final_{index},{len(test["final"]["ram"])},{cycles},{test.get("sr_mask", 65535)},{int(index >= external)}' + '}')
    text = (f'#define VECTOR_PROGRAM_BYTES {PROGRAM_BYTES}u\n' + '\n'.join(arrays) +
            '\nstatic const CorpusCase corpus_cases[] = {' + ',\n'.join(cases) + '};\n')
    return text, bytes(payload), fixture


def replay(fixture_name: str, project: Path | None = None) -> dict:
    project = project or ROOT / '.build' / 'cps1-vector-selftest' / fixture_name
    project.mkdir(parents=True, exist_ok=True)
    header, program, fixture = cases_header(fixture_name)
    cps1_build._engine(project, native=True)
    analysis = cps1_codegen.generate_m68k(project, program)
    (project / 'vector_fixture.h').write_text(header, encoding='utf-8')
    checks = (ROOT / 'native/cps1_vector_checks.c').as_posix()
    (project / 'CMakeLists.txt').write_text(f'''cmake_minimum_required(VERSION 3.20)
project(RetroCps1Vectors C)
set(CMAKE_C_STANDARD 11)
set(CMAKE_MSVC_RUNTIME_LIBRARY "MultiThreaded$<$<CONFIG:Debug>:Debug>")
file(GLOB STEPS "${{CMAKE_CURRENT_SOURCE_DIR}}/steps/cps1_step_*.c")
add_executable(checks "{checks}" engine/m68k/m68kcpu.c engine/m68k/m68kops.c cps1_native.c cps1_arithmetic.c ${{STEPS}})
target_include_directories(checks PRIVATE . engine/m68k)
target_compile_definitions(checks PRIVATE CPS1_NATIVE=1)
if(MSVC)
  target_compile_options(checks PRIVATE /utf-8 /wd4996 /wd4244 /wd4267)
  target_compile_definitions(checks PRIVATE __BYTE_ORDER__=1234 __ORDER_LITTLE_ENDIAN__=1234)
endif()
''', encoding='utf-8')
    cmake, generator = toolchain()
    run([cmake, '-S', project, '-B', project / 'build', '-G', generator, *cmake_target_args()], log=project / 'build.log')
    run([cmake, '--build', project / 'build', '--config', 'Release', '--parallel', build_jobs()], log=project / 'build.log')
    output = run([build_executable(project / 'build', 'checks')])
    result = json.loads(next(line for line in output.splitlines() if line.startswith('{')))
    result.update(fixture=fixture_name, source=fixture['source'], revision=fixture['revision'],
                  scope=fixture['scope'], excluded=fixture['excluded'], translated_rom_positions=analysis['translated_rom_positions'])
    (project / 'results.json').write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    return result


def summary(result: dict) -> str:
    totals, cases = result['totals'], result['cases']
    return (f"{result['fixture']}: {cases} vectors; native steps ran {totals['native_executed']}; state agrees with the vector: "
            f"native {totals['native_state']}, Musashi reference {totals['reference_state']}; clocks agree with the vector: "
            f"native {totals['native_clock']}, reference {totals['reference_clock']}; the two paths agree with each other: "
            f"{totals['paths_equal']} (clocks {totals['paths_clock_equal']})")


def problems(result: dict) -> list[str]:
    """What the run must satisfy: the translated steps follow every vector (registers, SR, PC, written bytes and clocks)
    except the trace-delivery vectors; every vector ran as a native step; the reference may differ from the vectors only
    in the named groups, and the two paths only differ where the reference does."""
    found = []
    for group in result['groups']:
        name, cases = group['group'], group['cases']
        if group['native_executed'] != cases:
            found.append(f'{name}: {cases - group["native_executed"]} vector(s) not run as a native step')
        if name == f'authored {TRACE_GROUP}':
            continue
        if group['native_state'] != cases or group['native_clock'] != cases:
            found.append(f'{name}: the native steps differ from the vectors (state {group["native_state"]}/{cases}, '
                         f'clocks {group["native_clock"]}/{cases})')
        reference_differs = group['reference_state'] != cases or group['reference_clock'] != cases
        if reference_differs and name not in REFERENCE_DEVIATIONS:
            found.append(f'{name}: the Musashi reference differs from the vectors (state {group["reference_state"]}/{cases}, '
                         f'clocks {group["reference_clock"]}/{cases}), a group not listed as a known deviation')
        if (group['paths_equal'] != cases or group['paths_clock_equal'] != cases) and not reference_differs:
            found.append(f'{name}: the two paths differ although the reference follows the vectors')
    return found


def main(names=None) -> int:
    results = [replay(name) for name in (names or FIXTURES)]
    failed = 0
    for result in results:
        print(summary(result))
        for text in problems(result):
            failed += 1
            print('PROBLEM', result['fixture'], text)
    print(json.dumps(results))
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:] or None))
