"""Cache the independent HuC6280 vectors (SingleStepTests/huc6280) for the PC Engine's check of the processor (gate G10).

The corpus is MIT licensed and generated by Mesen, not recorded from hardware: one file per opcode (00-FF), 2,500 vectors each, the
registers, the eight MPRs and the touched RAM cells before and after one instruction on a flat 2 MiB bus, with the cycle list. It
is read from the pinned revision's archive, every `v1/*.json.bin` file is kept as it is, and the whole is checked against a pinned
digest. It goes to `.deps/huc6280-vectors`; it is never in the repository or in a release (185 MB).

The digest is the SHA-256 of the lines "<file name> <SHA-256 of the file>" for the 256 files, in name order: it does not depend on
how the host compresses its archive. A corpus that does not match is refused.
"""
import argparse
import hashlib
import tarfile
import urllib.request
from pathlib import Path

REVISION = '4ce378e04e243437e6f74dfe76c3cb7c70e45bf1'
CORPUS_SHA256 = 'f5b70cc85766242f8249728b56d60e269e9ee1168c252f21bf9719ca5dc84ea0'
FILES = 256                      # v1/00.json.bin .. v1/ff.json.bin
BYTES = 185548937
ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / '.deps/huc6280-vectors'
URL = f'https://codeload.github.com/SingleStepTests/huc6280/tar.gz/{REVISION}'


def corpus_digest(hashes: dict[str, str]) -> str:
    """The pinned digest of {file name: SHA-256}."""
    return hashlib.sha256(''.join(f'{name} {hashes[name]}\n' for name in sorted(hashes)).encode('ascii')).hexdigest()


def folder() -> Path:
    return CACHE / REVISION / 'v1'


def cached() -> bool:
    return (CACHE / REVISION / 'DIGEST').is_file() and sum(1 for _ in folder().glob('*.json.bin')) == FILES


def fetch(expected_digest: str = CORPUS_SHA256) -> Path:
    target = CACHE / REVISION
    if cached():
        return folder()
    temporary = CACHE / f'{REVISION}.partial'
    vectors = temporary / 'v1'
    vectors.mkdir(parents=True, exist_ok=True)
    hashes, total = {}, 0
    with urllib.request.urlopen(URL, timeout=300) as response, tarfile.open(fileobj=response, mode='r|gz') as archive:
        for member in archive:
            path = Path(member.name)
            if member.isfile() and len(path.parts) == 2 and path.name == 'LICENSE':
                (temporary / 'LICENSE').write_bytes(archive.extractfile(member).read())
            elif member.isfile() and len(path.parts) == 3 and path.parts[1] == 'v1' and path.name.endswith('.json.bin'):
                data = archive.extractfile(member).read()
                (vectors / path.name).write_bytes(data)
                hashes[path.name] = hashlib.sha256(data).hexdigest()
                total += len(data)
    if len(hashes) != FILES or corpus_digest(hashes) != expected_digest:
        raise SystemExit(f'The HuC6280 corpus at {REVISION[:7]} does not match the pinned digest '
                         f'({len(hashes)} files, {total} bytes): refused, nothing kept.')
    (temporary / 'DIGEST').write_text(expected_digest + '\n', encoding='ascii')
    if target.exists():
        raise SystemExit(f'{target} exists and is incomplete: remove it and fetch again.')
    temporary.rename(target)
    return folder()


def main():
    argparse.ArgumentParser(description=__doc__.splitlines()[0]).parse_args()
    print(fetch())


if __name__ == '__main__':
    main()
