"""Assemble the GitHub Pages site from site/ and resized public media."""
from __future__ import annotations

import argparse
from pathlib import Path
import shutil

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "site"
DEFAULT_OUTPUT = ROOT / ".build" / "site"
MARKER = ".retrorecomp-site"
# Published name -> (tracked source, maximum width or None to copy unchanged).
MEDIA = {
    "logo.png": ("MEDIAS/RetroRecomp_logo_outlined.png", 480),
    "banner.png": ("MEDIAS/RetroRecomp_ban.png", 1200),
    "consoles.webp": ("MEDIAS/RetroRecomp_consoles.png", 1600),
    "converter.webp": ("MEDIAS/RetroRecomp_UI_1.1.5.jpg", 1162),
    "learning-cycle.webp": ("MEDIAS/RetroRecomp_learning_cycle.png", 1200),
    "icon-32.png": ("assets/Retro-Recomp-icon-32.png", None),
    "icon-64.png": ("assets/Retro-Recomp-icon-64.png", None),
    "icon-256.png": ("assets/Retro-Recomp-icon-256.png", None),
}


def export_image(source: Path, dest: Path, width: int | None) -> None:
    if width is None:
        shutil.copyfile(source, dest)
        return
    with Image.open(source) as image:
        if image.width > width:
            image = image.resize((width, round(image.height * width / image.width)), Image.LANCZOS)
        if dest.suffix == ".webp":
            image.save(dest, "WEBP", quality=82, method=6)
        else:
            image.save(dest, "PNG", optimize=True)


def build(output: Path) -> list[str]:
    output = output.resolve()
    if output == ROOT or ROOT.is_relative_to(output) or output == SOURCE.resolve():
        raise ValueError("The site output must be separate from the repository and site sources.")
    # Only clear a folder this script created, never an arbitrary directory.
    if output.exists() and any(output.iterdir()):
        if not (output / MARKER).is_file():
            raise ValueError(f"Refusing to overwrite a folder without {MARKER}: {output}")
        shutil.rmtree(output)
    shutil.copytree(SOURCE, output)
    (output / MARKER).write_text("Generated by tools/build_site.py\n", encoding="utf-8")
    (output / ".nojekyll").write_text("", encoding="utf-8")
    media = output / "media"
    media.mkdir(exist_ok=True)
    for name, (source, width) in MEDIA.items():
        export_image(ROOT / source, media / name, width)
    return sorted(p.relative_to(output).as_posix() for p in output.rglob("*") if p.is_file())


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", nargs="?", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    files = build(args.output)
    print(f"Built {len(files)} site files in {args.output}")


if __name__ == "__main__":
    main()
