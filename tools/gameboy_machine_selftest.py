"""The Game Boy machine's snapshot and digest (native/gb_machine_state.h, multiplayer rollback and the host's F8 / F9 for everyone).

native/gb_machine_checks.c runs three authored cartridges (MBC1, MBC3 with a clock, MBC5 on the colour hardware) in random slices with random
writes of the host between them, and checks: a run replayed from a snapshot gives the same digest, the same independent whole-state hash and the
same snapshot bytes after every step, on the same context and on one allocated apart; a snapshot every step changes nothing; a snapshot is the same
bytes over any buffer; a wrong size, a damaged header and another game's snapshot are refused and leave the context as it was; the digest moves with
every group of fields and not with the pictures. The runtime is built as the converter adapts it (`adapt_generated_project`).

    python -B tools/gameboy_machine_selftest.py [--again] [--rom CARTRIDGE.gb]    (writes .build/gb-machine-selftest/results.json)

`--rom` adds the player's own cartridge as a fourth variant (read from where it is, never copied into the repository).
"""
from pathlib import Path
import json
import sys
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from retrorecomp.platforms import build_executable, cmake_target_args
from retrorecomp.core import run
from retrorecomp.gameboy import _dependencies
from retrorecomp.gameboy_runtime import adapt_generated_project
from retrorecomp.resources import embed_resources
from retrorecomp.paths import ASSETS

WORK = ROOT / '.build/gb-machine-selftest'


def build(again: bool = False) -> Path:
    """`again`: only the checks are compiled again, in the project of the last run (the runtime part is regenerated by a normal run)."""
    WORK.mkdir(parents=True, exist_ok=True)
    if again and (WORK / 'build').is_dir():
        engine, compiler, sdl, cmake, generator = _dependencies(print)
        run([cmake, '--build', WORK / 'build', '--config', 'Release', '--target', 'retro_gb_machine_checks', '--parallel', '4'],
            log=WORK / 'build.log', timeout=900)
        return build_executable(WORK / 'build', 'retro_gb_machine_checks')
    rom = bytearray(32768)
    rom[0x100:0x104] = bytes.fromhex('00 c3 50 01')     # an authored program; the runtime only needs a valid image
    (WORK / 'fixture.gb').write_bytes(rom)
    engine, compiler, sdl, cmake, generator = _dependencies(print)
    log = WORK / 'build.log'
    run([compiler, WORK / 'fixture.gb', '-o', WORK, '--runtime-dir', engine / 'runtime',
         '--output-prefix', 'game', '--no-comments'], log=log, timeout=600)
    adapt_generated_project(WORK, 'machine-fixture', '0' * 64, 'Authored machine-state fixture')
    (WORK / 'game_resources.rc').write_text('1 RCDATA { 0 }\n', encoding='utf-8')
    embed_resources(WORK, {})
    with (WORK / 'CMakeLists.txt').open('a', encoding='utf-8') as out:
        out.write(f'''\nadd_executable(retro_gb_machine_checks "{(ASSETS / 'native/gb_machine_checks.c').as_posix()}")
target_link_libraries(retro_gb_machine_checks PRIVATE gbrt)
''')
    run([cmake, '-S', WORK, '-B', WORK / 'build', '-G', generator, *cmake_target_args(),
         f'-DCMAKE_PREFIX_PATH={sdl.as_posix()}'], log=log)
    run([cmake, '--build', WORK / 'build', '--config', 'Release', '--target', 'retro_gb_machine_checks',
         '--parallel', '4'], log=log, timeout=900)
    return build_executable(WORK / 'build', 'retro_gb_machine_checks')


def main():
    executable = build('--again' in sys.argv)
    rom = sys.argv[sys.argv.index('--rom') + 1] if '--rom' in sys.argv else None
    output = run([executable] + ([rom] if rom else []), timeout=1800)
    (WORK / 'checks.log').write_text(output, encoding='utf-8')
    result = json.loads(next(line for line in output.splitlines() if line.startswith('{')))
    (WORK / 'results.json').write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(result), flush=True)


if __name__ == '__main__':
    main()
