"""The Game Boy link cable (native/gb_link.h): two consoles of one process on one cable, checked with authored programs and no original byte.

native/gb_link_checks.c runs one small program on both consoles (START pressed makes a console the master, the other the slave) and checks the
byte exchange in both roles, the serial interrupts, a master with no partner, two masters, the replay of the pair from snapshots taken at frame
boundaries and in the middle of a frame (transfers in flight), and that the pair's digest moves with the second console. The runtime is built as the
converter adapts it (`adapt_generated_project`).

    python -B tools/gameboy_link_selftest.py [--again]    (writes .build/gb-link-selftest/results.json)

With `--model cgb` the Game Boy Color's checks (native/gbc_link_checks.c: the same cable on two Color consoles, every pairing of normal and double speed, normal and fast
serial clock) run on the runtime as the converter adapts it for the Color (writes .build/gbc-link-selftest/results.json).
"""
from pathlib import Path
import json
import sys
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from retrorecomp.platforms import build_executable, cmake_target_args
from retrorecomp.core import run
from retrorecomp.gameboy import COLOR, _dependencies
from retrorecomp.gameboy_runtime import adapt_generated_project
from retrorecomp.resources import embed_resources
from retrorecomp.paths import ASSETS

WORK = ROOT / '.build/gb-link-selftest'
COLOR_WORK = ROOT / '.build/gbc-link-selftest'


def build(again: bool = False, color: bool = False) -> Path:
    """`again`: only the checks are compiled again, in the project of the last run (the runtime part is regenerated by a normal run)."""
    work = COLOR_WORK if color else WORK
    checks = 'gbc_link_checks' if color else 'gb_link_checks'
    work.mkdir(parents=True, exist_ok=True)
    if again and (work / 'build').is_dir():
        engine, compiler, sdl, cmake, generator = _dependencies(print)
        run([cmake, '--build', work / 'build', '--config', 'Release', '--target', 'retro_gb_link_checks', '--parallel', '4'],
            log=work / 'build.log', timeout=900)
        return build_executable(work / 'build', 'retro_gb_link_checks')
    rom = bytearray(32768)
    rom[0x100:0x104] = bytes.fromhex('00 c3 50 01')     # an authored program; the runtime only needs a valid image
    if color:
        rom[0x143] = 0x80
    (work / 'fixture.gb').write_bytes(rom)
    engine, compiler, sdl, cmake, generator = _dependencies(print)
    log = work / 'build.log'
    run([compiler, work / 'fixture.gb', '-o', work, '--runtime-dir', engine / 'runtime',
         '--output-prefix', 'game', '--no-comments'], log=log, timeout=600)
    adapt_generated_project(work, 'link-fixture', '0' * 64, 'Authored link-cable fixture', variant=COLOR if color else None)
    (work / 'game_resources.rc').write_text('1 RCDATA { 0 }\n', encoding='utf-8')
    embed_resources(work, {})
    with (work / 'CMakeLists.txt').open('a', encoding='utf-8') as out:
        out.write(f'''\nadd_executable(retro_gb_link_checks "{(ASSETS / f'native/{checks}.c').as_posix()}")
target_link_libraries(retro_gb_link_checks PRIVATE gbrt)
''')
    run([cmake, '-S', work, '-B', work / 'build', '-G', generator, *cmake_target_args(),
         f'-DCMAKE_PREFIX_PATH={sdl.as_posix()}'], log=log)
    run([cmake, '--build', work / 'build', '--config', 'Release', '--target', 'retro_gb_link_checks',
         '--parallel', '4'], log=log, timeout=900)
    return build_executable(work / 'build', 'retro_gb_link_checks')


def main():
    color = '--model' in sys.argv and sys.argv[sys.argv.index('--model') + 1] == 'cgb'
    work = COLOR_WORK if color else WORK
    executable = build('--again' in sys.argv, color)
    output = run([executable], timeout=1800)
    (work / 'checks.log').write_text(output, encoding='utf-8')
    result = json.loads(next(line for line in output.splitlines() if line.startswith('{')))
    (work / 'results.json').write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(result), flush=True)


if __name__ == '__main__':
    main()
