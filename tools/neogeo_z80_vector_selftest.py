"""Independent Z80 vectors replayed through the Neo Geo Z80 generator path (gate G10, independent CPU evidence).

    python -B tools/fetch_z80_vectors.py            (once: caches a sample of the pinned corpus in .deps/z80-vectors)
    python -B tools/neogeo_z80_vector_selftest.py [--samples 32]

The corpus is SingleStepTests/z80 (MIT, generated by JSMoo, not recorded from hardware; synthetic instruction data, no cartridge),
a deterministic sample of every instruction family: the same corpus, the same vectors file, the same report and the same judging
rules as `tools/cps1_z80_vector_selftest.py`, whose `fetch`, `window`, `vectors_file`, `summary`, `problems` and pinned `BASELINE`
this tool imports (nothing is copied). What differs is the sound CPU of the board: the Neo Geo one is translated by the converter's
own `neogeo_z80.generate` (one guarded body per distinct opcode form found in the M1 and SM1 ROMs, operands read live; observed
RAM variants for the window at 0xf800) on a synthetic cartridge whose M1 ROM is the image holding one slot per opcode form of the
vectors, and dispatched by the patched Geolith core (`neogeo_build.prepare_project`). `native/neogeo_z80_vector_checks.c` runs every
vector on that path and on the same core with every instruction interpreted, on a flat 64 KiB bus whose ports answer from the vector,
and compares registers (WZ and the alternate set included), written bytes, ports and the clock count with the vector, and the two
paths with each other.

What it shows and what it does not: the behaviour of the translated bodies and of Geolith's Z80 (with the corrections of
`neogeo_z80.FIXES`) against an oracle neither was written from. P and Q (the undocumented flag-copy registers) are not compared: the
core has neither. It says nothing about the Neo Geo board, the YM2610 or the 68000 to Z80 command latch, hardware fidelity (the oracle
is JSMoo) or gameplay.
"""
from __future__ import annotations
import importlib.util
import json
from pathlib import Path
import struct
import sys
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from retrorecomp.core import run, toolchain
from retrorecomp.megadrive_z80 import opcode_key
from retrorecomp.neogeo_build import prepare_project
from retrorecomp.neogeo_z80 import generate
from retrorecomp.platforms import build_executable, build_jobs, cmake_target_args

_spec = importlib.util.spec_from_file_location('cps1_z80_vector_selftest', ROOT / 'tools' / 'cps1_z80_vector_selftest.py')
shared = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(shared)

M1_BYTES = 0x10000        # the smallest sound program a NEO container accepts; the image holds one 4-byte slot per opcode form
SM1_BYTES = 0x20000
RAM_FIRST = 0xf800        # the sound RAM window: code there runs through observed variants, below it through the M1 lookup
SLOT = shared.SLOT
NO_SLOT = shared.NO_SLOT


def prepare(cases: list[dict]):
    """(image, ram records, per-case slots, forms): one image slot per distinct opcode form of the vectors below the RAM window,
    one observed RAM variant per distinct (address, bytes) above it."""
    keys, slots, ram = {}, [], {}
    for case in cases:
        pc, raw = case['initial']['pc'], shared.window(case)
        key = opcode_key(raw)
        if key is None:
            slots.append(NO_SLOT)
        elif pc < RAM_FIRST:
            if key not in keys:
                keys[key] = len(keys) * SLOT
            slots.append(keys[key])
        else:
            slots.append(NO_SLOT)
            ram[(pc, raw)] = {'address': pc, 'bytes': raw.hex()}
    assert len(keys) * SLOT <= M1_BYTES, 'too many opcode forms for one image'
    image = bytearray(M1_BYTES)
    for (mask, raw), offset in keys.items():
        image[offset:offset + 4] = raw
    return bytes(image), list(ram.values()), slots, len(keys)


def write_cartridge(project: Path, image: bytes) -> None:
    """A NEO container (512 bytes of program, 128 KiB fixed, the image as sound program, 128 bytes of sprites) and a BIOS archive
    holding an empty SM1: authored, no game."""
    lengths = (512, 131072, M1_BYTES, 0, 0, 128)
    header = bytearray(4096)
    header[:4] = b'NEO\x01'
    struct.pack_into('<6I', header, 4, *lengths)
    (project / 'cartridge.neo').write_bytes(bytes(header) + bytes(512 + 131072) + image + bytes(128))
    with ZipFile(project / 'bios.zip', 'w') as archive:
        archive.writestr('sm1.sm1', bytes(SM1_BYTES))


def replay(samples: int = 32, project: Path | None = None) -> dict:
    project = project or ROOT / '.build' / 'neogeo-z80-vector-selftest'
    project.mkdir(parents=True, exist_ok=True)
    source = shared.fetch(samples)
    corpus = json.loads(source.read_text(encoding='utf-8'))
    cases = corpus['cases']
    image, ram, slots, forms = prepare(cases)
    write_cartridge(project, image)
    prepare_project(project, native=True, native_sound=True)
    analysis = generate(project, ROOT / '.deps/geolith-libretro', ram)
    shared.vectors_file(cases, slots, project / 'vectors.bin')
    checks = (ROOT / 'native/neogeo_z80_vector_checks.c').as_posix()
    (project / 'CMakeLists.txt').write_text(f'''cmake_minimum_required(VERSION 3.20)
project(RetroNgZ80Vectors LANGUAGES C)
set(CMAKE_C_STANDARD 11)
set(CMAKE_MSVC_RUNTIME_LIBRARY "MultiThreaded$<$<CONFIG:Debug>:Debug>")
add_executable(checks "{checks}" engine/z80/z80.c)
target_include_directories(checks PRIVATE . engine)
target_compile_definitions(checks PRIVATE __BYTE_ORDER__=1234 __ORDER_LITTLE_ENDIAN__=1234)
target_compile_options(checks PRIVATE "$<$<C_COMPILER_ID:MSVC>:/utf-8;/wd4996;/wd4244;/wd4267>")
''', encoding='utf-8')
    cmake, generator = toolchain()
    run([cmake, '-S', project, '-B', project / 'build', '-G', generator, *cmake_target_args()], log=project / 'build.log')
    run([cmake, '--build', project / 'build', '--config', 'Release', '--parallel', build_jobs()], log=project / 'build.log', timeout=1800)
    output = run([build_executable(project / 'build', 'checks'), project / 'vectors.bin'], timeout=900)
    result = json.loads(next(line for line in output.splitlines() if line.startswith('{')))
    result.update(corpus_revision=corpus['revision'], families_in_corpus=len(corpus['families']), samples_per_family=samples,
                  opcode_forms=forms, sound_ram_variants=len(ram), generated_native_bodies=analysis['structural_bodies'])
    (project / 'results.json').write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    return result


def main(argv=None) -> int:
    samples = 32
    if argv and argv[:1] == ['--samples']:
        samples = int(argv[1])
    result = replay(samples)
    print(shared.summary(result))
    failed = shared.problems(result)
    for text in failed:
        print('PROBLEM', text)
    print(json.dumps(result))
    return 1 if failed else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
