"""Independent reference model of the Nintendo GSU (Super FX), for the authored checks.

Every rule below is written from the GSU chapter of nocash's fullsnes
(problemkaputt.de/fullsnes.htm: "SNES Cart GSU-n ..." sections: I/O map, bitmap
ports, MOV/ALU/JMP/prefix/pseudo opcodes, code cache, pixel cache, timings).
Nothing here is read from, or generated by, the engine's superfx.c.

Where fullsnes is silent, the rule is the usual published behaviour of the
ISC-licensed ares implementation (consulted from memory of its documented
semantics, no code copied) and the case that depends on it carries
``ares=True`` so the report can count those assertions separately.

The model is a plain functional machine: one opcode byte is prefetched while
the previous one executes ("the byte after a jump/branch is executed before the
target", "STOP prefetches the byte at $+1 without executing it"), R15 reads as
the address of the next opcode, pixels are written straight to the bitmap.
Cycle counts are *not* simulated; the model only counts what the documentation
prices (opcode bytes fetched, extra multiplier clocks) and flags the opcodes
whose price fullsnes gives only as a range (``untimed``).
"""
import zlib

ROM_SIZE = 0x20000
RAM_SIZE = 0x20000
M16 = 0xFFFF


def s8(v):
    v &= 0xFF
    return v - 0x100 if v & 0x80 else v


def s16(v):
    v &= M16
    return v - 0x10000 if v & 0x8000 else v


class ModelError(Exception):
    pass


# ----------------------------------------------------------------------------
# assembler helpers (opcode numbers from the fullsnes opcode tables)
# ----------------------------------------------------------------------------
STOP, NOP, CACHE = b'\x00', b'\x01', b'\x02'
ALT1, ALT2, ALT3 = b'\x3d', b'\x3e', b'\x3f'
PREFIX = {0: b'', 1: ALT1, 2: ALT2, 3: ALT3}


def to(n):
    return bytes([0x10 + n])


def with_(n):
    return bytes([0x20 + n])


def frm(n):
    return bytes([0xB0 + n])


def op1(op, alt=0):
    return PREFIX[alt] + bytes([op])


def ibt(n, v):
    return bytes([0xA0 + n, v & 0xFF])


def iwt(n, v):
    return bytes([0xF0 + n, v & 0xFF, (v >> 8) & 0xFF])


def lms(n, kk):
    return ALT1 + bytes([0xA0 + n, kk])


def sms(n, kk):
    return ALT2 + bytes([0xA0 + n, kk])


def lm(n, addr):
    return ALT1 + bytes([0xF0 + n, addr & 0xFF, addr >> 8])


def sm(n, addr):
    return ALT2 + bytes([0xF0 + n, addr & 0xFF, addr >> 8])


def branch(op, off):
    return bytes([op, off & 0xFF])


BRA, BGE, BLT, BNE, BEQ, BPL, BMI, BCC, BCS, BVC, BVS = range(5, 16)
SFR_Z, SFR_CY, SFR_S, SFR_OV = 1 << 1, 1 << 2, 1 << 3, 1 << 4


class Gsu:
    """The architectural state plus the documented rules."""

    def __init__(self, rom, ram=None):
        if len(rom) != ROM_SIZE:
            raise ModelError('ROM image must be %d bytes' % ROM_SIZE)
        self.rom = rom
        self.ram = bytearray(ram if ram is not None else RAM_SIZE)
        self.r = [0] * 16
        self.z = self.cy = self.s = self.ov = 0
        self.alt1 = self.alt2 = self.b = 0
        self.sreg = self.dreg = 0
        self.pbr = self.rombr = self.rambr = 0
        self.cbr = 0
        self.colr = self.por = self.scbr = self.scmr = self.cfgr = self.clsr = 0
        self.irq = 0
        self.rom_bank = 0          # ROMBR in force when R14 was last written
        self.ramaddr = 0
        self.pipe = 0x01           # idle pipeline: the opcode after STOP/reset is a NOP
        self.r15_written = False
        self.cache = bytearray(512)
        self.cache_valid = [False] * 32
        self.fetch_count = 0       # opcode/operand bytes fetched (priced 1 clock when cached)
        self.hits = self.direct = self.fills = 0   # cache hits / ROM-or-RAM reads / 16-byte line fills
        self.r14_written = False
        self.ares_rules = set()    # rules taken from ares because fullsnes does not state them
        self.mult_extra = 0        # extra GSU clocks of MULT/UMULT/FMULT/LMULT
        self.untimed = set()       # opcode classes with only a documented cost range
        self.fetched = []          # (pbr, address) of every fetch
        self.irq_masked_flag_rule = True  # fullsnes: STOP sets SFR.IRQ even when masked
        self.dirty = set()
        self.running = False

    # ---- CPU-side (the S-CPU's view of $3000-$303F) ------------------------
    def cpu_write_reg(self, n, v):
        self.r[n] = v & M16
        if n == 14:
            self.rom_bank = self.rombr

    def cpu_cache_fill(self, data):
        self.cache = bytearray(data)
        self.cache_valid = [True] * 32

    def flush_cache(self):
        self.cache_valid = [False] * 32

    def set_sfr_flags(self, v):
        self.z, self.cy, self.s, self.ov = (v >> 1) & 1, (v >> 2) & 1, (v >> 3) & 1, (v >> 4) & 1

    def sfr(self):
        return ((self.z << 1) | (self.cy << 2) | (self.s << 3) | (self.ov << 4) |
                (self.running << 5) | (self.alt1 << 8) | (self.alt2 << 9) |
                (self.b << 12) | (self.irq << 15))

    # ---- memory ------------------------------------------------------------
    def rom_read(self, bank, addr):
        if bank < 0x40:                       # 00-3F:0000-7FFF, 32K LoROM chunks
            idx = ((bank & 0x3F) << 15) | (addr & 0x7FFF)
        elif bank < 0x60:                     # 40-5F:0000-FFFF, 64K chunks
            idx = ((bank - 0x40) << 16) | addr
        else:
            return 0
        return self.rom[idx & (ROM_SIZE - 1)]

    def ram_index(self, bank, addr):
        return ((bank & 1) << 16 | addr) & (RAM_SIZE - 1)

    def ram_read(self, addr):
        return self.ram[self.ram_index(self.rambr, addr & M16)]

    def ram_write(self, addr, v):
        i = self.ram_index(self.rambr, addr & M16)
        self.ram[i] = v & 0xFF
        self.dirty.add(i)

    def memory_byte(self, bank, addr):
        if bank <= 0x5F:
            return self.rom_read(bank, addr)
        return self.ram[self.ram_index(bank, addr)]

    def fetch(self, addr):
        self.fetch_count += 1
        self.fetched.append((self.pbr, addr))
        off = (addr - self.cbr) & M16
        if off < 512:
            line = (addr & 0x1FF) >> 4
            if self.cache_valid[line]:
                self.hits += 1
            else:
                self.fills += 1
                base = (self.cbr + (off & 0x1F0)) & M16
                for i in range(16):
                    self.cache[((base + i) & 0x1FF)] = self.memory_byte(self.pbr, (base + i) & M16)
                self.cache_valid[line] = True
            return self.cache[addr & 0x1FF]
        self.direct += 1
        return self.memory_byte(self.pbr, addr)

    # ---- registers ---------------------------------------------------------
    def put(self, n, v):
        self.r[n] = v & M16
        if n == 15:
            self.r15_written = True
        if n == 14:
            self.r14_written = True
            self.rom_bank = self.rombr        # opcode write to R14 reloads the ROM buffer

    def setsz(self, v):
        self.s = (v >> 15) & 1
        self.z = 1 if (v & M16) == 0 else 0

    def clear_prefix(self):
        self.alt1 = self.alt2 = self.b = 0
        self.sreg = self.dreg = 0

    def operand_byte(self):
        out = self.pipe
        self.r[15] = (self.r[15] + 1) & M16
        self.pipe = self.fetch(self.r[15])
        self.r15_written = False
        return out

    # ---- execution ---------------------------------------------------------
    def start(self):
        self.running = True
        self.pipe = 0x01

    def run(self, limit=2_000_000):
        count = 0
        while self.running:
            count += 1
            if count > limit:
                raise ModelError('program does not stop')
            self.step()

    def step(self):
        op = self.pipe
        self.pipe = self.fetch(self.r[15])
        self.r15_written = False
        self.execute(op)
        if not self.r15_written:
            self.r[15] = (self.r[15] + 1) & M16

    def execute(self, op):
        n = op & 15
        alt = self.alt1 | (self.alt2 << 1)
        src = self.r[self.sreg]
        if op == 0x00:                                  # STOP
            self.running = False
            self.irq = 1 if self.irq_masked_flag_rule or not (self.cfgr & 0x80) else self.irq
            self.pipe = 0x01
            self.clear_prefix()
        elif op == 0x01:                                # NOP
            self.clear_prefix()
        elif op == 0x02:                                # CACHE: CBR = R15 & FFF0, empty the cache
            self.cbr = self.r[15] & 0xFFF0
            self.flush_cache()
            self.clear_prefix()
        elif op == 0x03:                                # LSR
            self.cy = src & 1
            v = src >> 1
            self.put(self.dreg, v)
            self.setsz(v)
            self.clear_prefix()
        elif op == 0x04:                                # ROL
            v = ((src << 1) | self.cy) & M16
            self.cy = src >> 15
            self.put(self.dreg, v)
            self.setsz(v)
            self.clear_prefix()
        elif 0x05 <= op <= 0x0F:                        # branches keep the prefixes
            disp = s8(self.operand_byte())
            cond = {5: True, 6: self.s == self.ov, 7: self.s != self.ov, 8: not self.z,
                    9: bool(self.z), 10: not self.s, 11: bool(self.s), 12: not self.cy,
                    13: bool(self.cy), 14: not self.ov, 15: bool(self.ov)}[op]
            if cond:
                self.put(15, self.r[15] + disp)
        elif 0x10 <= op <= 0x1F:                        # TO / MOVE
            if self.b:
                self.put(n, src)
                self.clear_prefix()
            else:
                self.dreg = n
        elif 0x20 <= op <= 0x2F:                        # WITH
            self.sreg = self.dreg = n
            self.b = 1
        elif 0x30 <= op <= 0x3B:                        # STW / STB
            self.ramaddr = self.r[n]
            self.ram_write(self.ramaddr, src)
            if not self.alt1:
                self.ram_write(self.ramaddr ^ 1, src >> 8)
            self.untimed.add('ram_store')
            self.clear_prefix()
        elif op == 0x3C:                                # LOOP
            self.put(12, self.r[12] - 1)
            self.setsz(self.r[12])
            if not self.z:
                self.put(15, self.r[13])
            self.clear_prefix()
        elif op == 0x3D:
            self.alt1 = 1
            self.b = 0
        elif op == 0x3E:
            self.alt2 = 1
            self.b = 0
        elif op == 0x3F:
            self.alt1 = self.alt2 = 1
            self.b = 0
        elif 0x40 <= op <= 0x4B:                        # LDW / LDB
            self.ramaddr = self.r[n]
            v = self.ram_read(self.ramaddr)
            if not self.alt1:
                v |= self.ram_read(self.ramaddr ^ 1) << 8
            self.put(self.dreg, v)
            self.untimed.add('ram_load')
            self.clear_prefix()
        elif op == 0x4C:                                # PLOT / RPIX
            if self.alt1:
                v = self.rpix()
                self.put(self.dreg, v)
                self.s = 0
                self.z = 1 if v == 0 else 0
            else:
                self.plot()
            self.untimed.add('pixel')
            self.clear_prefix()
        elif op == 0x4D:                                # SWAP
            v = ((src >> 8) | (src << 8)) & M16
            self.put(self.dreg, v)
            self.setsz(v)
            self.clear_prefix()
        elif op == 0x4E:                                # COLOR / CMODE
            if self.alt1:
                self.por = src & 0x1F
            else:
                self.colour_input(src & 0xFF)
            self.clear_prefix()
        elif op == 0x4F:                                # NOT
            v = src ^ M16
            self.put(self.dreg, v)
            self.setsz(v)
            self.clear_prefix()
        elif 0x50 <= op <= 0x5F:                        # ADD / ADC (register or #n)
            q = n if self.alt2 else self.r[n]
            cin = self.cy if self.alt1 else 0
            total = src + q + cin
            res = total & M16
            self.ov = 1 if (~(src ^ q) & (src ^ res) & 0x8000) else 0
            self.cy = 1 if total > M16 else 0
            self.put(self.dreg, res)
            self.setsz(res)
            self.clear_prefix()
        elif 0x60 <= op <= 0x6F:                        # SUB / SBC / CMP (register or #n)
            if alt == 3:
                q = self.r[n]                           # CMP Rn
            else:
                q = n if self.alt2 else self.r[n]
            borrow = (1 - self.cy) if alt == 1 else 0   # SBC subtracts NOT carry
            total = src - q - borrow
            res = total & M16
            self.ov = 1 if ((src ^ q) & (src ^ res) & 0x8000) else 0
            self.cy = 1 if total >= 0 else 0
            if alt != 3:
                self.put(self.dreg, res)
            self.setsz(res)
            self.clear_prefix()
        elif op == 0x70:                                # MERGE
            v = (self.r[7] & 0xFF00) | (self.r[8] >> 8)
            self.put(self.dreg, v)
            self.s = 1 if v & 0x8080 else 0
            self.ov = 1 if v & 0xC0C0 else 0
            self.cy = 1 if v & 0xE0E0 else 0
            self.z = 1 if v & 0xF0F0 else 0             # sic: set when NOT zero (fullsnes)
            self.clear_prefix()
        elif 0x71 <= op <= 0x7F:                        # AND / BIC
            q = n if self.alt2 else self.r[n]
            v = src & (q ^ M16 if self.alt1 else q)
            self.put(self.dreg, v)
            self.setsz(v)
            self.clear_prefix()
        elif 0x80 <= op <= 0x8F:                        # MULT / UMULT
            q = n if self.alt2 else self.r[n]
            if self.alt1:
                v = ((src & 0xFF) * (q & 0xFF)) & M16
            else:
                v = (s8(src) * s8(q)) & M16
            self.put(self.dreg, v)
            self.setsz(v)
            if not (self.cfgr & 0x20):
                self.mult_extra += 1
            self.clear_prefix()
        elif op == 0x90:                                # SBK
            self.ram_write(self.ramaddr, src)
            self.ram_write(self.ramaddr ^ 1, src >> 8)
            self.untimed.add('ram_store')
            self.clear_prefix()
        elif 0x91 <= op <= 0x94:                        # LINK
            self.put(11, self.r[15] + n)
            self.clear_prefix()
        elif op == 0x95:                                # SEX
            v = s8(src) & M16
            self.put(self.dreg, v)
            self.setsz(v)
            self.clear_prefix()
        elif op == 0x96:                                # ASR / DIV2
            self.cy = src & 1
            v = (s16(src) >> 1) & M16
            if self.alt1 and src == M16:
                v = 0                                   # DIV2: -1 -> 0
            self.put(self.dreg, v)
            self.setsz(v)
            self.clear_prefix()
        elif op == 0x97:                                # ROR
            v = (self.cy << 15) | (src >> 1)
            self.cy = src & 1
            self.put(self.dreg, v)
            self.setsz(v)
            self.clear_prefix()
        elif 0x98 <= op <= 0x9D:                        # JMP / LJMP
            if self.alt1:
                self.pbr = self.r[n] & 0x7F
                self.put(15, src)
                self.cbr = self.r[15] & 0xFFF0
                self.flush_cache()
            else:
                self.put(15, self.r[n])
            self.clear_prefix()
        elif op == 0x9E:                                # LOB
            v = src & 0xFF
            self.put(self.dreg, v)
            self.s = (v >> 7) & 1
            self.z = 1 if v == 0 else 0
            self.clear_prefix()
        elif op == 0x9F:                                # FMULT / LMULT
            prod = s16(src) * s16(self.r[6])
            lo, hi = prod & M16, (prod >> 16) & M16
            if self.alt1:
                self.put(4, lo)
                self.put(self.dreg, hi)
            elif self.dreg != 4:                        # fullsnes: FMULT with Rd=R4 leaves R4
                self.put(self.dreg, hi)
            self.setsz(hi)
            self.cy = (prod >> 15) & 1                  # fullsnes: C updated, rule not stated (ares: bit 15)
            self.ares_rules.add('fmult/lmult carry')
            self.mult_extra += 3 if (self.cfgr & 0x20) else 7
            self.clear_prefix()
        elif 0xA0 <= op <= 0xAF:                        # IBT / LMS / SMS
            if self.alt1:
                self.ramaddr = (self.operand_byte() << 1) & M16
                self.put(n, self.ram_read(self.ramaddr) | self.ram_read(self.ramaddr ^ 1) << 8)
                self.untimed.add('ram_load')
            elif self.alt2:
                self.ramaddr = (self.operand_byte() << 1) & M16
                self.ram_write(self.ramaddr, self.r[n])
                self.ram_write(self.ramaddr ^ 1, self.r[n] >> 8)
                self.untimed.add('ram_store')
            else:
                self.put(n, s8(self.operand_byte()))
            self.clear_prefix()
        elif 0xB0 <= op <= 0xBF:                        # FROM / MOVES
            if self.b:
                v = self.r[n]
                self.put(self.dreg, v)
                self.ov = (v >> 7) & 1
                self.setsz(v)
                self.clear_prefix()
            else:
                self.sreg = n
        elif op == 0xC0:                                # HIB
            v = src >> 8
            self.put(self.dreg, v)
            self.s = (v >> 7) & 1
            self.z = 1 if v == 0 else 0
            self.clear_prefix()
        elif 0xC1 <= op <= 0xCF:                        # OR / XOR
            q = n if self.alt2 else self.r[n]
            v = (src ^ q) if self.alt1 else (src | q)
            self.put(self.dreg, v)
            self.setsz(v)
            self.clear_prefix()
        elif 0xD0 <= op <= 0xDE:                        # INC
            self.put(n, self.r[n] + 1)
            self.setsz(self.r[n])
            self.clear_prefix()
        elif op == 0xDF:                                # GETC / RAMB / ROMB
            if not self.alt2:
                self.colour_input(self.rom_byte())
                self.untimed.add('rom_buffer')
            elif not self.alt1:
                self.rambr = src & 1
            else:
                self.rombr = src & 0x7F
            self.clear_prefix()
        elif 0xE0 <= op <= 0xEE:                        # DEC
            self.put(n, self.r[n] - 1)
            self.setsz(self.r[n])
            self.clear_prefix()
        elif op == 0xEF:                                # GETB / GETBH / GETBL / GETBS
            b = self.rom_byte()
            old = self.r[self.dreg]
            v = (b, (b << 8) | (old & 0xFF), (old & 0xFF00) | b, s8(b) & M16)[alt]
            self.put(self.dreg, v)
            self.untimed.add('rom_buffer')
            self.clear_prefix()
        else:                                           # F0-FF: IWT / LM / SM
            if self.alt1:
                self.ramaddr = self.operand_byte()
                self.ramaddr |= self.operand_byte() << 8
                self.put(n, self.ram_read(self.ramaddr) | self.ram_read(self.ramaddr ^ 1) << 8)
                self.untimed.add('ram_load')
            elif self.alt2:
                self.ramaddr = self.operand_byte()
                self.ramaddr |= self.operand_byte() << 8
                self.ram_write(self.ramaddr, self.r[n])
                self.ram_write(self.ramaddr ^ 1, self.r[n] >> 8)
                self.untimed.add('ram_store')
            else:
                lo = self.operand_byte()
                self.put(n, lo | (self.operand_byte() << 8))
            self.clear_prefix()

    # ---- ROM buffer --------------------------------------------------------
    def rom_byte(self):
        """GETB family/GETC read [ROMBR-at-the-last-R14-write : R14]."""
        return self.rom_read(self.rom_bank, self.r[14])

    # ---- bitmap ------------------------------------------------------------
    def bits_per_pixel(self):
        return {0: 2, 1: 4, 2: 4, 3: 8}[self.scmr & 3]

    def tile_number(self, x, y):
        height = 3 if (self.por & 0x10) else (((self.scmr >> 5) & 1) << 1) | ((self.scmr >> 2) & 1)
        if height == 3:
            return ((y // 0x80) * 0x200 + (x // 0x80) * 0x100 +
                    ((y // 8) & 0x0F) * 0x10 + ((x // 8) & 0x0F))
        per_column = (0x10, 0x14, 0x18)[height]
        return (x // 8) * per_column + (y // 8)

    def pixel_row_address(self, x, y):
        bpp = self.bits_per_pixel()
        return self.tile_number(x, y) * bpp * 8 + self.scbr * 0x400 + (y & 7) * 2

    def colour_input(self, data):
        if self.por & 4:                          # high-nibble: replace incoming LSB by incoming MSB
            data = (data & 0xF0) | (data >> 4)
        if self.por & 8:                          # freeze-high: only the LSB of COLOR changes
            self.colr = (self.colr & 0xF0) | (data & 0x0F)
        else:
            self.colr = data & 0xFF

    def plot(self):
        x, y = self.r[1] & 0xFF, self.r[2] & 0xFF
        bpp = self.bits_per_pixel()
        colour = self.colr
        if self.por & 2 and bpp != 8 and ((self.r[1] ^ self.r[2]) & 1):
            colour = self.colr >> 4               # dither: COLOR/10h
        draw = True
        if not self.por & 1:                      # colour 0 is skipped, R1 still advances
            test = (1 << bpp) - 1
            if bpp == 8 and self.por & 8:
                test = 0x0F
            if self.colr & test == 0:
                draw = False
        if draw:
            value = colour & ((1 << bpp) - 1)
            base = self.pixel_row_address(x, y)
            for plane in range(bpp):
                addr = (base + ((plane >> 1) << 4) + (plane & 1)) & (RAM_SIZE - 1)
                bit = 0x80 >> (x & 7)
                byte = self.ram[addr]
                byte = (byte | bit) if (value >> plane) & 1 else (byte & ~bit)
                self.ram[addr] = byte & 0xFF
                self.dirty.add(addr)
        self.r[1] = (self.r[1] + 1) & M16

    def rpix(self):
        x, y = self.r[1] & 0xFF, self.r[2] & 0xFF
        base = self.pixel_row_address(x, y)
        value = 0
        for plane in range(self.bits_per_pixel()):
            addr = (base + ((plane >> 1) << 4) + (plane & 1)) & (RAM_SIZE - 1)
            value |= ((self.ram[addr] >> (7 - (x & 7))) & 1) << plane
        return value


def ram_crc(ram):
    return zlib.crc32(bytes(ram)) & 0xFFFFFFFF
