"""Atari ST native code on Hatari's own instruction handlers (MIT script; what it writes is compiled with Hatari, GPL-2.0): one routine per observed
instruction, chained from instruction to instruction.

The ST's reference machine is Hatari, whose 68000 is WinUAE's cycle-exact core: one C function per opcode family, generated by gencpu (`op_<opcode>_<table>_ff`, listed
by the cycle-exact 68000 table `op_smalltbl_14`). Native code must make the same bus accesses at the same cycles as the reference (the ST's 4-cycle bus alignment, the wait
states of the video, MFP and PSG registers), so a *form* is the very handler Hatari's table would call for its opcode, its generated text compiled again with the opcode as a literal: the prefetch, the cycle counting
and the bus waits stay Hatari's, in the same order. This is Hatari's code specialised, not a translation.

That is why the guard is one comparison. A handler is correct for its opcode at any address and with any extension words (it reads them on the bus), so all that decides
whether it may run is the opcode the CPU has latched: a word rewritten in memory, by anything, needs no tracking. An *instruction* (one per address and opcode observed,
`rr_st_at_<pc>_<opcode>`) runs its handler, counts, and goes straight on to the instruction it knows comes next when the CPU is there with that opcode latched and the work of
the 68000 loop between the two has nothing to do but its bookkeeping (`rr_st_quiet`, `rr_st_next` in step_semantics.h). Anything else returns to the loop, which then does that
work as it always does. `rr_st_lookup` is the way in, from the loop's hook.

`load_opcode_map` reads the table the reference player writes at conversion time (`--opcode-map`: `<opcode hex> <entry index>` into `op_smalltbl_14`, `-` for an opcode
Hatari's table sends to its illegal-instruction handlers) and names the entries from the cpustbl.c of Hatari's build; nothing of Hatari is copied here. The decoder of the
recompiler only tells the length and the target of an observed instruction, at conversion time: it is not in the game.
"""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

from . import m68k_observed
from .core import run
from .m68000 import mnemonic_names
from .megadrive_codegen import write_changed

FORMAT = 2
PARTS = 16
_MAP: dict[int, str] = {}
_MAP_SHA256 = ''
_TEXT: dict[str, str] = {}
_HANDLER = re.compile(r'op_[0-9a-f]{4}_[0-9]{1,2}_ff')
_DEFINITION = re.compile(r'^void REGPARAM2 (op_[0-9a-f]{4}_(?:13|14)_ff)\(uae_u32 opcode\)\n\{\n(.*?)^\}\n', re.M | re.S)


def table_handlers(cpustbl: Path) -> list[str]:
    """The handler of every entry of `op_smalltbl_14` (the cycle-exact 68000 table) in the cpustbl.c gencpu wrote in Hatari's
    build: the no-return handler (the one the cycle-exact loop calls), in entry order. gencpu shares a handler between tables when
    their code is the same (TRAP: `op_4e40_13_ff`), so the name is read, never derived from the opcode."""
    text = Path(cpustbl).read_text(encoding='utf-8')
    start = text.index('const struct cputbl op_smalltbl_14[] = {')
    body = text[start:text.index('{ 0 }};', start)]   # the table ends with its zero entry
    names = []
    for line in body.splitlines()[1:]:
        fields = [field.strip() for field in line.strip().lstrip('{').split(',')]
        if len(fields) < 3 or not fields[0]:
            continue
        noret = fields[1]
        names.append(noret if noret != 'NULL' else fields[0])
    return names


def load_opcode_map(path: Path, cpustbl: Path) -> dict[int, str]:
    """The opcode -> handler table of Hatari's cycle-exact 68000; every one of the 65,536 opcodes must be there. `path` is what the
    reference player wrote (`<opcode hex> <entry index>` or `-`), `cpustbl` the generated table that names the entries."""
    global _MAP, _MAP_SHA256, _TEXT
    handlers = table_handlers(cpustbl)
    # The text of the handlers gencpu wrote for this CPU, beside the table. A handler that is not there stays a call (`_form`).
    emulator = Path(cpustbl).with_name('cpuemu_13.c')
    source = emulator.read_text(encoding='utf-8') if emulator.is_file() else ''
    _TEXT = dict(_DEFINITION.findall(source))
    table = {}
    text = Path(path).read_text(encoding='ascii')
    for line in text.splitlines():
        code, entry = line.split()
        if entry == '-':
            table[int(code, 16)] = '-'
            continue
        index = int(entry)
        if not 0 <= index < len(handlers) or not _HANDLER.fullmatch(handlers[index]):
            raise ValueError(f'Invalid Hatari handler entry {entry} for opcode {code}.')
        table[int(code, 16)] = handlers[index]
    if len(table) != 65536:
        raise ValueError('The Hatari opcode table is incomplete.')
    digest = hashlib.sha256(text.encode() + b'\0' + '\n'.join(handlers).encode() + b'\0' + source.encode())
    _MAP, _MAP_SHA256 = table, digest.hexdigest()
    return table


# step_semantics.h: Hatari's CPU headers, which declare every generated handler (cputbl.h of its build). `rr_st_quiet` and `rr_st_next` are the work of `m68k_run_1_ce`
# between two instructions when nothing is due. The test comes first and changes nothing, so the loop still does all of it for an instruction after which something is due: the
# wait states of an access (never on this CPU), an event whose clock has passed, an MFP update, a special flag, an interrupt level above the mask. Then the statements are the
# loop's, in its order, and those of its next turn.
SEMANTICS = """#pragma once
#include <stdint.h>
#include "main.h"
#include "sysdeps.h"
#include "hatari-glue.h"
#include "maccess.h"
#include "memory.h"
#include "custom.h"
#include "newcpu.h"
#include "cpu_prefetch.h"
#include "cputbl.h"
#include "debugmem.h"
#include "events.h"
#include "cycles.h"
#include "m68000.h"
#include "cycInt.h"
#include "mfp.h"
extern uint64_t rr_st_native_total;
static inline __attribute__((always_inline)) int rr_st_quiet(void) {
    /* An interrupt level below the CPU's mask is the usual state of an ST (HBL pending): `do_specialties` then does nothing, as `time_for_interrupt` answers 0. */
    return !(regs.spcflags | regs.loop_mode | regs.memory_waitstate_cycles | MFP_UpdateNeeded) && regs.ipl[0] <= regs.intmask && regs.ipl[0] != 7 && regs.ce020extracycles < 16 &&
           CycInt_ActiveInt_Cycles > ((CyclesGlobalClockCounter + (uint64_t)(currcycle * 2 / CYCLE_UNIT)) << CYCINT_SHIFT);
}
static inline __attribute__((always_inline)) int rr_st_next(uint32_t pc, uint32_t opcode) {
    if (m68k_getpc() != pc || regs.ir != opcode) return 0;
    regs.ird = regs.opcode;
    regs.instruction_cnt++;
    M68000_AddCycles_CE(currcycle * 2 / CYCLE_UNIT);
    regs.ipl[0] = regs.ipl[1];
    regs.ipl[1] = 0;
    regs.opcode = regs.ir;
    currcycle = 0;
    regs.instruction_pc = pc;
    return 1;
}
#if defined(__clang__)
#define RR_ST_NEXT [[clang::musttail]] return
#else
#define RR_ST_NEXT return
#endif
#ifdef RR_ST_FORMS
/* Macros gencpu writes at the head of the handlers' file, and the functions of steps/bus.c in place of the pointers. */
#define SET_ALWAYS_CFLG(x) SET_CFLG(x)
#define SET_ALWAYS_NFLG(x) SET_NFLG(x)
void rr_st_internal(int clocks);
uae_u32 rr_st_prefetch(int o);
uae_u32 rr_st_get_word(uaecptr addr);
uae_u32 rr_st_get_byte(uaecptr addr);
void rr_st_put_word(uaecptr addr, uae_u32 v);
void rr_st_put_byte(uaecptr addr, uae_u32 v);
#define get_word_ce000_prefetch rr_st_prefetch
#define do_cycles_ce000_internal rr_st_internal
#define x_get_word rr_st_get_word
#define x_put_word rr_st_put_word
#define x_get_byte rr_st_get_byte
#define x_put_byte rr_st_put_byte
/* A fault is rare: its exits out of the way of the hot path. This changes no statement. */
#define hardware_bus_error __builtin_expect(hardware_bus_error, 0)
extern void exception3_read_access(uae_u32 opcode, uaecptr addr, int size, int fc) __attribute__((cold));
extern void exception3_write_access(uae_u32 opcode, uaecptr addr, int size, uae_u32 val, int fc) __attribute__((cold));
extern void exception3_read_prefetch(uae_u32 opcode, uaecptr addr) __attribute__((cold));
extern void exception3_read_prefetch_only(uae_u32 opcode, uaecptr addr) __attribute__((cold));
extern void exception2_read(uae_u32 opcode, uaecptr addr, int size, int fc) __attribute__((cold));
extern void exception2_write(uae_u32 opcode, uaecptr addr, int size, uae_u32 val, int fc) __attribute__((cold));
extern void exception2_fetch_opcode(uae_u32 opcode, int offset, int pcoffset) __attribute__((cold));
extern void exception2_fetch(uae_u32 opcode, int offset, int pcoffset) __attribute__((cold));
#endif
"""


# steps/bus.c: what the forms share, one copy of it: the bus without the calls and pointers
# in between: the code of `mem_access_delay_*` (newcpu.c), `wait_cpu_cycle_*` (custom.c) and `memory_get_*` (memory.c) of Hatari's cycle-exact 68000, on the bank type the ST's memory
# has. A blitter at work (its own functions behind the pointers) and any other bank type go through Hatari's functions.
BUS = """#include "step_semantics.h"
#include "blitter.h"
uint64_t rr_st_native_total;
extern uae_u32 extra_cycle;
static inline void cycles_add(int cycles) {
    currcycle += cycles + extra_cycle;
    extra_cycle = 0;
}
void rr_st_internal(int clocks) {
    if (currprefs.m68k_speed < 0) return;
    if (BlitterPhase) x_do_cycles(clocks * cpucycleunit);
    else cycles_add(clocks * cpucycleunit);
}
static inline int direct(uaecptr addr) { return !BlitterPhase && ce_banktype[addr >> 16] == CE_MEMBANK_CHIP16; }
static inline void slot_wait(void) {
    uint64_t slot = (CyclesGlobalClockCounter + currcycle * 2 / CYCLE_UNIT) & 3;
    if (slot != 0) cycles_add((4 - slot) * cpucycleunit);
}
static inline void after_read(evt_t now, int ipl) {
    cycles_add(2 * CYCLE_UNIT);
    if (now == regs.ipl_evt && regs.ipl_pin_change_evt > now + cpuipldelay2) regs.ipl[0] = ipl;
    if (BlitterPhase) Blitter_HOG_CPU_mem_access_after(1);
}
static inline void after_write(evt_t now, int ipl) {
    cycles_add(2 * CYCLE_UNIT);
    if (now == regs.ipl_evt) regs.ipl[0] = ipl;
    if (BlitterPhase) Blitter_HOG_CPU_mem_access_after(1);
}
static inline uae_u32 wordi(uaecptr addr) {
    if (!direct(addr)) return mem_access_delay_wordi_read(addr);
    int ipl = regs.ipl[0];
    evt_t now = currcycle;
    uae_u32 v;
    slot_wait();
    addrbank *ab = &get_mem_bank(addr);
    v = ab->baseaddr_direct_r ? do_get_mem_word((uae_u16 *)(ab->baseaddr_direct_r + ((addr - ab->startaccessmask) & ab->mask))) : call_mem_get_func(ab->wgeti, addr);
    after_read(now, ipl);
    regs.db = v;
    regs.read_buffer = v;
    return v;
}
uae_u32 rr_st_get_word(uaecptr addr) {
    if (!direct(addr)) return mem_access_delay_word_read(addr);
    int ipl = regs.ipl[0];
    evt_t now = currcycle;
    uae_u32 v;
    slot_wait();
    addrbank *ab = &get_mem_bank(addr);
    v = ab->baseaddr_direct_r ? do_get_mem_word((uae_u16 *)(ab->baseaddr_direct_r + ((addr - ab->startaccessmask) & ab->mask))) : call_mem_get_func(ab->wget, addr);
    after_read(now, ipl);
    regs.db = v;
    regs.read_buffer = v;
    return v;
}
uae_u32 rr_st_get_byte(uaecptr addr) {
    if (!direct(addr)) return mem_access_delay_byte_read(addr);
    int ipl = regs.ipl[0];
    evt_t now = currcycle;
    uae_u32 v;
    slot_wait();
    addrbank *ab = &get_mem_bank(addr);
    v = ab->baseaddr_direct_r ? *(ab->baseaddr_direct_r + ((addr - ab->startaccessmask) & ab->mask)) : call_mem_get_func(ab->bget, addr);
    after_read(now, ipl);
    regs.db = (v << 8) | v;
    regs.read_buffer = v;
    return v;
}
void rr_st_put_word(uaecptr addr, uae_u32 v) {
    if (!direct(addr)) { mem_access_delay_word_write(addr, v); return; }
    regs.db = v;
    regs.write_buffer = v;
    int ipl = regs.ipl[0];
    evt_t now = currcycle;
    slot_wait();
    addrbank *ab = &get_mem_bank(addr);
    if (ab->baseaddr_direct_w) do_put_mem_word((uae_u16 *)(ab->baseaddr_direct_w + ((addr - ab->startaccessmask) & ab->mask)), v);
    else call_mem_put_func(ab->wput, addr, v);
    after_write(now, ipl);
}
void rr_st_put_byte(uaecptr addr, uae_u32 v) {
    if (!direct(addr)) { mem_access_delay_byte_write(addr, v); return; }
    regs.db = (v << 8) | v;
    regs.write_buffer = v;
    int ipl = regs.ipl[0];
    evt_t now = currcycle;
    slot_wait();
    addrbank *ab = &get_mem_bank(addr);
    if (ab->baseaddr_direct_w) *(ab->baseaddr_direct_w + ((addr - ab->startaccessmask) & ab->mask)) = (uae_u8)v;
    else call_mem_put_func(ab->bput, addr, v);
    after_write(now, ipl);
}
uae_u32 rr_st_prefetch(int o) {
    if (BlitterPhase) return get_word_ce000_prefetch(o);
    uae_u32 v = regs.irc;
    regs.irc = regs.read_buffer = regs.db = wordi(m68k_getpci() + o);
    return v;
}
"""


def _semantics(prefix: str, alias) -> str:
    return SEMANTICS


def form_definition(symbol: str, opcode: int) -> str:
    """The form of this opcode: the text of Hatari's handler with the opcode as a literal, or a call of the handler when its text is not known."""
    handler = _MAP.get(opcode, '-')
    if handler == '-':
        # An opcode Hatari's table sends to its illegal-instruction handlers never becomes native code (native_samples leaves it on the counted interpreter); reaching here is a
        # generator error.
        raise ValueError(f'Atari ST: no Hatari handler for opcode {opcode:04x}.')
    body = _TEXT.get(handler)
    if body is None:
        return f'void {symbol}(void) {{ {handler}(0x{opcode:04x}); }}\n'
    return f'void {symbol}(void) {{\n\tuae_u32 opcode = 0x{opcode:04x};\n{body}}}\n'


def hatari_bodies(engine: Path, prefix: str) -> m68k_observed.InstructionBodies:
    """The `ObservedCode.bodies` entry point of the Atari ST: every decoded mnemonic is accepted (Hatari's table handles them all). Call `load_opcode_map` first."""
    if not _MAP:
        raise ValueError('Load the Hatari opcode table first.')
    names = mnemonic_names(engine)
    return m68k_observed.InstructionBodies(names, {name: '' for name in names}, '', '', _MAP_SHA256, semantics_text=_semantics)


def native_samples(samples: list) -> list:
    """The observed instructions that can become native: those whose opcode has a handler in Hatari's table."""
    return [(pc, words) for pc, words in samples if _MAP.get(int(words[:4], 16), '-') != '-']


def _symbol(prefix: str, pc: int, opcode: int) -> str:
    return f'{prefix}at_{pc:06x}_{opcode:04x}'


def _form_symbol(prefix: str, opcode: int) -> str:
    return f'{prefix}form_{opcode:04x}'


def _instruction(prefix: str, pc: int, opcode: int, following: list) -> str:
    chain = ''.join(f'    if (rr_st_next(0x{next_pc:x}, 0x{other:04x})) RR_ST_NEXT {_symbol(prefix, next_pc, other)}();\n' for next_pc, other in following)
    next_part = f'    if (!rr_st_quiet()) return;\n{chain}' if chain else ''
    return f'void {_symbol(prefix, pc, opcode)}(void) {{\n    {_form_symbol(prefix, opcode)}();\n    rr_st_native_total++;\n{next_part}}}\n'


def write_forms(project: Path, opcodes, *, observed) -> None:
    """The forms of these opcodes (`steps/partNN.c`)."""
    steps = project / 'steps'
    steps.mkdir(parents=True, exist_ok=True)
    chunks = [[] for _ in range(PARTS)]
    for opcode in sorted(set(opcodes)):
        chunks[(opcode >> 1) % PARTS].append(form_definition(_form_symbol(observed.prefix, opcode), opcode))
    for n, chunk in enumerate(chunks):
        write_changed(steps / f'part{n:02}{observed.source_extension}', '#define RR_ST_FORMS 1\n' + observed.steps_head + ''.join(chunk))
    write_changed(steps / f'bus{observed.source_extension}', BUS)


def write_steps(project: Path, samples: list, *, observed, decode_tool: Path) -> dict:
    """Decode the observed instructions, then write the forms (`steps/partNN.c`), the instructions in address order (`steps/chainNN.c`) and the index that finds one from a pc and an
    opcode (`steps/index.c`)."""
    prefix = observed.prefix
    decoded = []
    if samples:
        listing = project / 'snapshots.txt'
        listing.write_text(''.join(f'{pc:06x} {words}\n' for pc, words in sorted(set(samples))), encoding='ascii')
        run([decode_tool, listing, project / 'decoded.json'], log=project / 'decode.log')
        decoded = json.loads((project / 'decoded.json').read_text(encoding='utf-8'))
    words = {(ins['addr'], tuple(ins['words'][:ins['word_count']])) for ins in decoded}
    # What may follow each (pc, opcode): the targets its variants name first (a loop's branch), then where they fall through.
    following: dict[tuple[int, int], list] = {}
    for ins in decoded:
        places = following.setdefault((ins['addr'], ins['words'][0]), [[], []])
        if ins['has_target'] and ins['target_addr'] & 0xffffff not in places[0]:
            places[0].append(ins['target_addr'] & 0xffffff)
        fall = (ins['addr'] + ins['byte_length']) & 0xffffff
        if fall not in places[1]:
            places[1].append(fall)
    instructions = sorted(following)
    opcodes_at: dict[int, list] = {}
    for pc, opcode in instructions:
        opcodes_at.setdefault(pc, []).append(opcode)
    write_forms(project, [opcode for _, opcode in instructions], observed=observed)
    steps = project / 'steps'
    # Neighbours in memory stay in one file: a chain's jumps stay short.
    size = max(1, (len(instructions) + PARTS - 1) // PARTS)
    for n in range(PARTS):
        text, declared, forms_declared = [], set(), set()
        for pc, opcode in instructions[n * size:(n + 1) * size]:
            places = following[(pc, opcode)]
            ordered = list(dict.fromkeys(places[0] + places[1]))
            chain = [(place, other) for place in ordered for other in opcodes_at.get(place, [])]
            text.extend(f'void {_symbol(prefix, *item)}(void);\n' for item in sorted(set(chain) - declared))
            declared |= set(chain) | {(pc, opcode)}
            if opcode not in forms_declared:
                text.append(f'void {_form_symbol(prefix, opcode)}(void);\n')
                forms_declared.add(opcode)
            text.append(_instruction(prefix, pc, opcode, chain))
        write_changed(steps / f'chain{n:02}{observed.source_extension}', observed.steps_head + ''.join(text))
    groups = []
    for index, (pc, _) in enumerate(instructions):
        if groups and groups[-1][0] == pc:
            groups[-1][2] += 1
        else:
            groups.append([pc, index, 1])
    pages: dict[int, dict] = {}
    for index, (pc, _, _) in enumerate(groups):
        page = pages.setdefault(pc >> 12, {'base': index, 'slots': {}})
        page['slots'][(pc & 0xfff) >> 1] = index - page['base'] + 1
    source = ['#include <stddef.h>\n#include <stdint.h>\ntypedef void (*RrStCode)(void);\n']
    source.extend(f'void {_symbol(prefix, pc, opcode)}(void);\n' for pc, opcode in instructions)
    source.append('static const struct {uint16_t opcode;RrStCode run;} entries[]={'
                  + (',\n'.join(f'{{0x{opcode:04x},{_symbol(prefix, pc, opcode)}}}' for pc, opcode in instructions) or '{0,NULL}') + '};\n')
    source.append('static const struct {uint32_t start,count;} groups[]={' + (','.join(f'{{{start},{count}}}' for _, start, count in groups) or '{0,0}') + '};\n')
    for number, page in sorted(pages.items()):
        source.append(f'static const uint16_t page_{number:x}[2048]={{' + ','.join(f'[{slot}]={value}' for slot, value in sorted(page['slots'].items())) + '};\n')
    source.append('static const struct {uint32_t base;const uint16_t *slots;} pages[4096]={'
                  + ','.join(f'[{number}]={{{page["base"]},page_{number:x}}}' for number, page in sorted(pages.items())) + '};\n')
    source.append("""RrStCode rr_st_lookup(uint32_t pc,uint32_t opcode) {
    pc&=0xffffffu;
    if(pc&1u)return NULL;
    const uint16_t *slots=pages[pc>>12].slots;
    if(!slots)return NULL;
    unsigned slot=slots[(pc&0xfffu)>>1];
    if(!slot)return NULL;
    unsigned group=pages[pc>>12].base+slot-1u;
    for(unsigned k=0;k<groups[group].count;++k)
        if(entries[groups[group].start+k].opcode==opcode)return entries[groups[group].start+k].run;
    return NULL;
}
""")
    write_changed(steps / f'index{INDEX_EXTENSION}', ''.join(source))
    return {'samples': len(samples), 'instructions': len(words), 'native_instructions': len(instructions), 'forms': len({opcode for _, opcode in instructions}), 'pcs': len(groups)}


