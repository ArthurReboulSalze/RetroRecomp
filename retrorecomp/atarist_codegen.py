def index_tail(links: list) -> str:
    """After the lookup: the accessors the session's step hook uses (the step type stays inside the index)."""
    return ('void (*rr_st_step_of(const RrStStep *s))(uint32_t) { return s->run; }\n'
            'uint32_t rr_st_step_opcode(const RrStStep *s) { return s->instruction.words[0]; }\n')


