"""Atari ST native steps on Hatari's own instruction handlers (MIT script; the steps it writes are compiled with Hatari, GPL-2.0):
the hooks the shared observed-code generator calls.

The ST's reference machine is Hatari, whose 68000 is WinUAE's cycle-exact core: one C function per opcode family, generated by
gencpu (`op_<opcode>_<table>_ff`, listed by the cycle-exact 68000 table `op_smalltbl_14`). A native step must make the same bus accesses at
the same cycles as the reference (the ST's 4-cycle bus alignment, the wait states of the video, MFP and PSG registers), so it calls
the very handler Hatari's table would call for its opcode, with the opcode as a literal, instead of going through the table: the
prefetch, the cycle counting and the bus waits stay Hatari's. The shared generator (`m68k_observed.write_steps`) groups the observed
instructions into forms by the decoder's structural key (it starts with the opcode word), so every form has exactly one handler.
The live-word guard of the shared index keeps a changed instruction on the counted interpreter, and the session also requires the
prefetched opcode to be the step's own.

`load_opcode_map` reads the table the reference player writes at conversion time (`--opcode-map`: `<opcode hex> <entry index>` into
`op_smalltbl_14`, `-` for an opcode Hatari's table sends to its illegal-instruction handlers) and names the entries from the cpustbl.c
of Hatari's build; nothing of Hatari is copied here.
"""
from __future__ import annotations

import hashlib
import re
from pathlib import Path

from . import m68k_observed
from .m68000 import mnemonic_names

FORMAT = 1
_MAP: dict[int, str] = {}
_MAP_SHA256 = ''
_HANDLER = re.compile(r'op_[0-9a-f]{4}_[0-9]{1,2}_ff')


def table_handlers(cpustbl: Path) -> list[str]:
    """The handler of every entry of `op_smalltbl_14` (the cycle-exact 68000 table) in the cpustbl.c gencpu wrote in Hatari's
    build: the no-return handler (the one the cycle-exact loop calls), in entry order. gencpu shares a handler between tables when
    their code is the same (TRAP: `op_4e40_13_ff`), so the name is read, never derived from the opcode."""
    text = Path(cpustbl).read_text(encoding='utf-8')
    start = text.index('const struct cputbl op_smalltbl_14[] = {')
    body = text[start:text.index('{ 0 }};', start)]   # the table ends with its zero entry
    names = []
    for line in body.splitlines()[1:]:
        fields = [field.strip() for field in line.strip().lstrip('{').split(',')]
        if len(fields) < 3 or not fields[0]:
            continue
        noret = fields[1]
        names.append(noret if noret != 'NULL' else fields[0])
    return names


def load_opcode_map(path: Path, cpustbl: Path) -> dict[int, str]:
    """The opcode -> handler table of Hatari's cycle-exact 68000; every one of the 65,536 opcodes must be there. `path` is what the
    reference player wrote (`<opcode hex> <entry index>` or `-`), `cpustbl` the generated table that names the entries."""
    global _MAP, _MAP_SHA256
    handlers = table_handlers(cpustbl)
    table = {}
    text = Path(path).read_text(encoding='ascii')
    for line in text.splitlines():
        code, entry = line.split()
        if entry == '-':
            table[int(code, 16)] = '-'
            continue
        index = int(entry)
        if not 0 <= index < len(handlers) or not _HANDLER.fullmatch(handlers[index]):
            raise ValueError(f'Invalid Hatari handler entry {entry} for opcode {code}.')
        table[int(code, 16)] = handlers[index]
    if len(table) != 65536:
        raise ValueError('The Hatari opcode table is incomplete.')
    digest = hashlib.sha256(text.encode() + b'\0' + '\n'.join(handlers).encode())
    _MAP, _MAP_SHA256 = table, digest.hexdigest()
    return table


def _semantics(prefix: str, alias) -> str:
    """step_semantics.h: Hatari's CPU headers, which declare every generated handler (cputbl.h of its build)."""
    return ('#pragma once\n#include <stdint.h>\n#include "sysconfig.h"\n#include "sysdeps.h"\n#include "options_cpu.h"\n'
            '#include "memory.h"\n#include "newcpu.h"\n#include "cputbl.h"\n')


def _step(symbol: str, ins: dict, name: str, body: str) -> tuple[str, str]:
    opcode = ins['words'][0]
    handler = _MAP.get(opcode, '-')
    if handler == '-':
        # An opcode Hatari's table sends to its illegal-instruction handlers never becomes a step (native_samples leaves it on the
        # counted interpreter); reaching here is a generator error, not a step to write.
        raise ValueError(f'Atari ST: no Hatari handler for opcode {opcode:04x}.')
    return (f'void {symbol}(uint32_t op) {{ {handler}(op); }}\n', f'void {symbol}(uint32_t op);\n')


def hatari_bodies(engine: Path, prefix: str) -> m68k_observed.InstructionBodies:
    """The `ObservedCode.bodies` entry point of the Atari ST: every decoded mnemonic is accepted (Hatari's table handles them
    all); the steps and their header come from the hooks. Call `load_opcode_map` first."""
    if not _MAP:
        raise ValueError('Load the Hatari opcode table first.')
    names = mnemonic_names(engine)
    return m68k_observed.InstructionBodies(names, {name: '' for name in names}, '', '', _MAP_SHA256,
                                           step_text=_step, semantics_text=_semantics)


def native_samples(samples: list) -> list:
    """The observed instructions that can become steps: those whose opcode has a handler in Hatari's table."""
    return [(pc, words) for pc, words in samples if _MAP.get(int(words[:4], 16), '-') != '-']


