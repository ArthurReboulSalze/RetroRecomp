"""What the Capcom arcade catalogues (CPS-1 and CPS-2) have in common: reading the pinned JSON and the files a set loads.

The catalogues are generated by tools/build_cps1_catalogue.py and tools/build_cps2_catalogue.py from MAME's BSD-3-Clause drivers
(see licenses/cps1-machine.md); they describe boards and ROM layouts, never ROM contents.
"""
import hashlib
import json

from .paths import ASSETS


def load_catalogue(resource: str, sha256: str, revision: str, max_bytes: int, label: str) -> dict:
    """The bundled catalogue, checked against its pinned hash and revision before anything is read from it."""
    with (ASSETS / resource).open('rb') as stream:
        raw = stream.read(max_bytes + 1)
    if len(raw) > max_bytes or hashlib.sha256(raw).hexdigest() != sha256:
        raise ValueError(f'{label} board catalogue failed its integrity check.')
    data = json.loads(raw)
    if (data.get('schema') != 1 or data.get('source', {}).get('revision') != revision
            or not isinstance(data.get('games'), list)):
        raise ValueError(f'Invalid {label} board catalogue.')
    return data


def files(game: dict, label: str = 'CPS-1') -> list[dict]:
    """Distinct ROM files a set loads. Undumped parts cannot be required.

    A file's size is its first load plus the CONTINUE/IGNORE parts that follow;
    RELOAD reads it again from the start.
    """
    result, known = [], {}
    for region in game['regions']:
        current, counting = None, False
        for load in region['loads']:
            if load['op'] in ('continue', 'ignore'):
                if current is None:
                    raise ValueError(f'Invalid {label} ROM continuation in ' + game['set'] + '.')
                if counting:
                    current['bytes'] += load['bytes']
            elif load['op'] == 'reload':
                counting = False
            elif 'name' not in load:
                current, counting = None, False
            elif load.get('no_dump'):
                current, counting = {'bytes': 0}, False
            elif (key := (load['name'], load['crc32'])) in known:
                current, counting = known[key], False
            else:
                current = known[key] = {'name': load['name'], 'bytes': load['bytes'], 'crc32': load['crc32'],
                                        'sha1': load['sha1'], 'region': region['tag'],
                                        'bad_dump': bool(load.get('bad_dump'))}
                result.append(current)
                counting = True
    return result


def program_files(game: dict, label: str = 'CPS-1') -> list[dict]:
    return [item for item in files(game, label) if item['region'] == 'maincpu']
