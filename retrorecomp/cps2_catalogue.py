"""ROM-free, pinned CPS-2 board descriptors; identification needs no toolchain and no key.

Generated by tools/build_cps2_catalogue.py from MAME's BSD-3-Clause CPS-2 driver (see licenses/cps1-machine.md). It describes ROM layouts,
not a list of qualified games, and holds no encryption key: each set's 20-byte key is a file of the player's own romset (MAME's `key`
ROM region), recognised here only by its name, size and hashes. The CPS-B board and the graphics mapper are those of the CPS-1 catalogue.
"""
from functools import lru_cache
from .capcom_catalogue import files as capcom_files, load_catalogue, program_files as capcom_program_files

RESOURCE = 'assets/cps2-catalogue.json'
SHA256 = 'dbd62286ae876fa36e13ed3ca3b90fd8c3435987dab4f2647a32de66ba06388f'
MAME_REVISION = '61a222977fd29f22ce11fbea3f7c290fd7ced091'
MAX_BYTES = 4 * 1024 * 1024
KEY_BYTES = 20
REASONS = {
    'bootleg_or_hack': 'Bootleg and modified sets are outside the supported CPS-2 scope.',
    'not_working': 'This set is not working in its reference description.',
    'dead_board': 'Boards whose decryption key was lost (a dead battery) and run a replacement program are outside the CPS-2 scope.',
    'network_adapter': 'Sets that need the CPS-2 network adapter are not supported yet.',
    'other_hardware': 'This set uses hardware outside the supported CPS-2 scope.',
    'special_init': 'This set needs an input (a spinner or a paddle) or a board variant that is not supported yet.',
    'incomplete_dump': 'Part of this set has never been dumped.'}


@lru_cache(maxsize=1)
def catalogue() -> dict:
    return load_catalogue(RESOURCE, SHA256, MAME_REVISION, MAX_BYTES, 'CPS-2')


def games() -> list[dict]:
    return catalogue()['games']


@lru_cache(maxsize=1)
def by_set() -> dict:
    return {game['set']: game for game in games()}


def files(game: dict) -> list[dict]:
    """Distinct files a set loads, the key file included (region `key`)."""
    return capcom_files(game, 'CPS-2')


def program_files(game: dict) -> list[dict]:
    return capcom_program_files(game, 'CPS-2')


def key_file(game: dict) -> dict:
    """The set's key file as the catalogue knows it (name, size 20, CRC32, SHA-1): never its contents."""
    keys = [item for item in files(game) if item['region'] == 'key']
    if len(keys) != 1 or keys[0]['bytes'] != KEY_BYTES:
        raise ValueError('CPS-2 set ' + game['set'] + ' has no key file in the catalogue.')
    return keys[0]


def supported(game: dict) -> bool:
    return game['support'] == 'phase1'


def unsupported_reason(game: dict) -> str:
    return '' if supported(game) else REASONS.get(game['reason'], 'This CPS-2 set is not supported yet.')
