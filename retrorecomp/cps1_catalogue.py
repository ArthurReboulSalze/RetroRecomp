"""ROM-free, pinned CPS-1 board descriptors; identification needs no toolchain.

Generated by tools/build_cps1_catalogue.py from MAME's BSD-3-Clause CPS-1
driver (see licenses/cps1-machine.md). It describes boards and ROM layouts,
not a list of qualified games.
"""
from functools import lru_cache
import hashlib
import json
from .paths import ASSETS

RESOURCE = 'assets/cps1-catalogue.json'
SHA256 = 'a9534c512a1db2e2f67d1205839174bc11df7fb069f5b8f4115a0496bf35cfb1'
MAME_REVISION = '61a222977fd29f22ce11fbea3f7c290fd7ced091'
MAX_BYTES = 2 * 1024 * 1024
# Phase 1 runs standard 10/12 MHz boards: 68000, Z80, YM2151, OKI MSM6295.
REASONS = {
    'qsound': 'QSound boards (Kabuki-encrypted Z80 and QSound DSP) are not supported yet.',
    'dial': 'Forgotten Worlds boards need the rotary dial controller, which is not supported yet.',
    'eeprom': 'Pang! 3 boards (serial EEPROM, encrypted graphics) are not supported yet.',
    'timekeeper': 'Ganbare! Marine Kun boards (timekeeper RAM, raster interrupt) are not supported yet.',
    'bootleg_or_hack': 'Bootleg and modified sets are outside the supported CPS-1 scope.',
    'not_working': 'This set is not working in its reference description.',
    'cps_changer': 'CPS Changer home cartridges are outside the supported CPS-1 scope.',
    'special_init': 'This revision needs board-specific start-up handling that is not supported yet.',
    'other_hardware': 'This set uses modified hardware outside the supported CPS-1 scope.',
    'incomplete_dump': 'Part of this set has never been dumped.'}


@lru_cache(maxsize=1)
def catalogue() -> dict:
    with (ASSETS / RESOURCE).open('rb') as stream:
        raw = stream.read(MAX_BYTES + 1)
    if len(raw) > MAX_BYTES or hashlib.sha256(raw).hexdigest() != SHA256:
        raise ValueError('CPS-1 board catalogue failed its integrity check.')
    data = json.loads(raw)
    if (data.get('schema') != 1 or data.get('source', {}).get('revision') != MAME_REVISION
            or not isinstance(data.get('games'), list)):
        raise ValueError('Invalid CPS-1 board catalogue.')
    return data


def games() -> list[dict]:
    return catalogue()['games']


@lru_cache(maxsize=1)
def by_set() -> dict:
    return {game['set']: game for game in games()}


def files(game: dict) -> list[dict]:
    """Distinct ROM files a set loads. Undumped parts cannot be required.

    A file's size is its first load plus the CONTINUE/IGNORE parts that follow;
    RELOAD reads it again from the start.
    """
    result, known = [], {}
    for region in game['regions']:
        current, counting = None, False
        for load in region['loads']:
            if load['op'] in ('continue', 'ignore'):
                if current is None:
                    raise ValueError('Invalid CPS-1 ROM continuation in ' + game['set'] + '.')
                if counting:
                    current['bytes'] += load['bytes']
            elif load['op'] == 'reload':
                counting = False
            elif 'name' not in load:
                current, counting = None, False
            elif load.get('no_dump'):
                current, counting = {'bytes': 0}, False
            elif (key := (load['name'], load['crc32'])) in known:
                current, counting = known[key], False
            else:
                current = known[key] = {'name': load['name'], 'bytes': load['bytes'], 'crc32': load['crc32'],
                                        'sha1': load['sha1'], 'region': region['tag'],
                                        'bad_dump': bool(load.get('bad_dump'))}
                result.append(current)
                counting = True
    return result


def program_files(game: dict) -> list[dict]:
    return [item for item in files(game) if item['region'] == 'maincpu']


def dips(game: dict) -> list[dict]:
    """The set's named DIP switches with MAME's settings, in MAME's order."""
    return catalogue()['dip_blocks'].get(game['input'], [])


def supported(game: dict) -> bool:
    return game['support'] == 'phase1'


def qualification_candidate(game: dict) -> bool:
    """MAME-guessed graphics mappers and suspect dumps never count as evidence."""
    return supported(game) and game['mapper_verified'] and not any(item['bad_dump'] for item in files(game))


def unsupported_reason(game: dict) -> str:
    return '' if supported(game) else REASONS.get(game['reason'], 'This CPS-1 set is not supported yet.')
