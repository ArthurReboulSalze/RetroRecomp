"""The Amstrad CPC's keyboard as the converter types it (docs/AMSTRAD_CPC.md): the boot key sequence of a game, from the start
command its disk's catalogue gives (retrorecomp/cpc_disk.py), written as generated/boot_keys.h for the player shell
(native/hostkit/adapters/rrhk_boot_keys.h). MIT, Retro-Recomp.

HOST_TO_CPC is native/hostkit/adapters/rrhk_cpc_keys.h's table (the host key at each CPC key's position; tests/test_cpc_keys.py
checks they are equal); CHARACTERS says which CPC key, shifted or not, types each character the CPC's UK keyboard has. A
character is typed through the host key of its CPC key, with Left Shift when it is shifted, so the adapter maps it as it maps
the player's own typing. A character with no key refuses the sequence: the conversion never types something else.
"""
from __future__ import annotations

# SDL scancode -> CPC key name (CPC_KEY_<name> of native/cpc_machine/cpc_ppi.h).
HOST_TO_CPC = {
    **{4 + i: chr(ord('A') + i) for i in range(26)},
    **{30 + i: str((i + 1) % 10) for i in range(10)},
    40: 'RETURN', 41: 'ESC', 42: 'DEL', 43: 'TAB', 44: 'SPACE', 45: 'MINUS', 46: 'CARET', 47: 'AT', 48: 'LBRACKET',
    49: 'RBRACKET', 50: 'RBRACKET', 51: 'COLON', 52: 'SEMICOLON', 54: 'COMMA', 55: 'DOT', 56: 'SLASH', 57: 'CAPSLOCK',
    76: 'CLR', 79: 'RIGHT', 80: 'LEFT', 81: 'DOWN', 82: 'UP', 88: 'ENTER',
    **{89 + i: f'F{i + 1}' for i in range(9)}, 98: 'F0', 99: 'FDOT', 100: 'BACKSLASH',
    224: 'CONTROL', 225: 'SHIFT', 226: 'COPY', 228: 'CONTROL', 229: 'SHIFT',
}
LEFT_SHIFT = 225

# Character -> (CPC key, shifted): the CPC 6128's UK keyboard. Letters are typed unshifted (BASIC reads its keywords and AMSDOS
# its file names in either case).
CHARACTERS = {
    **{c: (c.upper(), False) for c in 'abcdefghijklmnopqrstuvwxyz'},
    **{c: (c, False) for c in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ'},
    **{d: (d, False) for d in '0123456789'},
    '!': ('1', True), '"': ('2', True), '#': ('3', True), '$': ('4', True), '%': ('5', True), '&': ('6', True),
    "'": ('7', True), '(': ('8', True), ')': ('9', True), '_': ('0', True),
    '-': ('MINUS', False), '=': ('MINUS', True), '^': ('CARET', False),
    '@': ('AT', False), '|': ('AT', True), '[': ('LBRACKET', False), '{': ('LBRACKET', True),
    ':': ('COLON', False), '*': ('COLON', True), ';': ('SEMICOLON', False), '+': ('SEMICOLON', True),
    ']': ('RBRACKET', False), '}': ('RBRACKET', True),
    ',': ('COMMA', False), '<': ('COMMA', True), '.': ('DOT', False), '>': ('DOT', True),
    '/': ('SLASH', False), '?': ('SLASH', True), '\\': ('BACKSLASH', False), '`': ('BACKSLASH', True),
    ' ': ('SPACE', False), '\n': ('RETURN', False),
}

# The sequence's timing (the interface specialist's review of 21 Nov 2026): each key 2 frames down, 2 frames all up. The first
# key waits for the firmware's « Ready »; BOOT_FRAME is the frame BASIC is ready on a 6128 with AMSDOS, to be measured on the
# player's firmware (Bomb Jack is the check).
HOLD_FRAMES = 2
GAP_FRAMES = 2
BOOT_FRAME = 150


def _host_key(cpc_key: str) -> int:
    """The host key that types `cpc_key` (the first in scancode order: the US position before the ISO one)."""
    for scancode, name in sorted(HOST_TO_CPC.items()):
        if name == cpc_key:
            return scancode
    raise KeyError(cpc_key)


def boot_sequence(text: str) -> tuple[tuple[int, bool], ...]:
    """(scancode, shift) for each character of `text`; ValueError naming a character the CPC's keyboard has no key for."""
    keys = []
    for character in text:
        if character not in CHARACTERS:
            raise ValueError(f'the CPC keyboard cannot type {character!r}')
        cpc_key, shifted = CHARACTERS[character]
        keys.append((_host_key(cpc_key), shifted))
    return tuple(keys)


def start_text(run_command: str | None) -> str:
    """The text a disk's start command types: the command and RETURN, or nothing for an undecided disk (the player types)."""
    return run_command + '\n' if run_command else ''


def boot_keys_header(text: str, start_frame: int = BOOT_FRAME, hold: int = HOLD_FRAMES, gap: int = GAP_FRAMES) -> str:
    """generated/boot_keys.h: `rr_boot_keys` for the player shell (count 0 for no text)."""
    keys = boot_sequence(text)
    if not (0 <= start_frame <= 0xFFFF and 1 <= hold <= 255 and 1 <= gap <= 255 and len(keys) <= 0xFFFF):
        raise ValueError('a boot key sequence starts within 65,535 frames, holds and gaps 1 to 255 frames')
    shown = text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
    lines = ['/* Generated by retrorecomp/cpc_keys.py: the boot key sequence of this game (native/hostkit/adapters/rrhk_boot_keys.h). */',
             f'/* "{shown}" */', '#include "rrhk_boot_keys.h"']
    if keys:
        items = ', '.join(f'{{ {scancode}, {int(shift)} }}' for scancode, shift in keys)
        lines.append(f'static const RrhkBootKey rr_boot_key_list[{len(keys)}] = {{ {items} }};')
        lines.append(f'static const RrhkBootKeys rr_boot_keys = {{ {start_frame}, {hold}, {gap}, {len(keys)}, rr_boot_key_list }};')
    else:
        lines.append(f'static const RrhkBootKeys rr_boot_keys = {{ {start_frame}, {hold}, {gap}, 0, 0 }};')
    return '\n'.join(lines) + '\n'
