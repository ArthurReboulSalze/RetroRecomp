"""Quick-state serialisers for the NES machine, written from the struct definitions.

The machine keeps its state in plain C structs (CPU, bus, cartridge, PPU, APU,
audio, VRC7). Copying a struct whole would put its compiler padding in the file.
This module reads the definitions from the staged sources and writes, for each
one, a field by field writer, reader and size, so every byte of a state is
defined by construction: a member that is not copied is not in the file, and
padding never is. A definition it cannot read (a pointer, a bit-field, a type
whose size depends on the compiler) stops the staging with an error instead of
being copied raw. Members that must not be saved are named in `SKIPPED`.
"""
from __future__ import annotations

import re

from .core import ConversionError

# Types with the same size on Windows and Linux (a state is replayed across both).
FIXED_TYPES = {'uint8_t', 'int8_t', 'uint16_t', 'int16_t', 'uint32_t', 'int32_t', 'uint64_t', 'int64_t',
               'bool', 'char', 'int', 'unsigned', 'float', 'double'}

# Members the state does not carry, with the reason.
SKIPPED = {
    ('HwCart', 'prg'): 'host pointer: the loaded cartridge provides it',
    ('HwCart', 'chr'): 'host pointer: the loaded cartridge provides it',
    ('OPLL', 'conv'): 'host pointer: the fixed-rate VRC7 core has no converter',
    ('OPLL_SLOT', 'patch'): 'host pointer: saved as an index by the VRC7 writer',
    ('OPLL_SLOT', 'wave_table'): 'host pointer: saved as an index by the VRC7 writer',
    ('RrAudio', 'ring'): 'queued host audio belongs to the discarded timeline',
    ('RrAudio', 'head'): 'queued host audio belongs to the discarded timeline',
    ('RrAudio', 'tail'): 'queued host audio belongs to the discarded timeline',
}

PREAMBLE = '''/* Generated by retrorecomp/nes_state_layout.py from the struct definitions of this build:
 * field by field, no compiler padding, no host pointer. Do not edit. */
#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <string.h>
#if !(defined(__BYTE_ORDER__) && __BYTE_ORDER__ == __ORDER_LITTLE_ENDIAN__) && !defined(_WIN32)
#error "Quick states are little-endian"
#endif
#define RR_STATE_FIELD(type, member) sizeof(((type *)0)->member)
'''


def _strip(text: str) -> str:
    return re.sub(r'/\*.*?\*/|//[^\n]*', ' ', text, flags=re.S)


def _matching(text: str, start: int) -> int:
    """Index of the brace that closes the one at `start`."""
    depth = 0
    for index in range(start, len(text)):
        if text[index] == '{':
            depth += 1
        elif text[index] == '}':
            depth -= 1
            if depth == 0:
                return index
    raise ConversionError('NES state layout: an unbalanced brace in a struct definition')


def _split_top(text: str, separator: str) -> list[str]:
    parts, depth, current = [], 0, ''
    for char in text:
        if char in '{[(':
            depth += 1
        elif char in '}])':
            depth -= 1
        if char == separator and depth == 0:
            parts.append(current)
            current = ''
        else:
            current += char
    parts.append(current)
    return parts


class Struct:
    def __init__(self, name: str, items: list):
        self.name = name
        self.items = items   # ('directive', text) | ('field', type, member, array) | ('nested', items, member)


def _body(owner: str, text: str) -> list:
    """The members of a struct body, directives kept in place."""
    items = []
    lines = text.split('\n')
    chunk = ''
    for line in lines:
        if line.lstrip().startswith('#'):
            if chunk.strip():
                raise ConversionError(f'NES state layout: {owner}: a conditional inside a declaration')
            items.append(('directive', line.strip()))
            continue
        chunk += line + '\n'
        # Declarations end at ';' outside braces.
        while True:
            depth, end = 0, -1
            for index, char in enumerate(chunk):
                if char == '{':
                    depth += 1
                elif char == '}':
                    depth -= 1
                elif char == ';' and depth == 0:
                    end = index
                    break
            if end < 0:
                break
            items.extend(_declaration(owner, chunk[:end]))
            chunk = chunk[end + 1:]
    if chunk.strip():
        raise ConversionError(f'NES state layout: {owner}: text after the last declaration: {chunk.strip()[:40]!r}')
    return items


def _declaration(owner: str, text: str) -> list:
    text = ' '.join(text.split())
    if not text:
        return []
    nested = re.match(r'^(?:struct|union)\s*\{', text)
    if nested:
        if text.startswith('union'):
            raise ConversionError(f'NES state layout: {owner}: a union is not serialised')
        start = text.index('{')
        end = _matching(text, start)
        name = text[end + 1:].strip()
        if not re.fullmatch(r'[A-Za-z_]\w*', name):
            raise ConversionError(f'NES state layout: {owner}: an anonymous struct member must be a plain name')
        return [('nested', _body(f'{owner}.{name}', text[start + 1:end]), name)]
    if ':' in text:
        raise ConversionError(f'NES state layout: {owner}: a bit-field is not serialised ({text[:40]!r})')
    words = re.match(r'^((?:(?:const|volatile|struct)\s+)*)(unsigned(?:\s+int)?(?=\s)|[A-Za-z_]\w*)\s*(.*)$', text)
    if not words:
        raise ConversionError(f'NES state layout: {owner}: cannot read the declaration {text[:40]!r}')
    type_name = 'unsigned' if words.group(2).startswith('unsigned') else words.group(2)
    rest = words.group(3)
    result = []
    for declarator in _split_top(rest, ','):
        declarator = declarator.strip()
        match = re.fullmatch(r'(\**)\s*([A-Za-z_]\w*)\s*((?:\[[^\]]+\]\s*)*)', declarator)
        if not match:
            raise ConversionError(f'NES state layout: {owner}: cannot read the member {declarator!r}')
        stars, member, dims = match.groups()
        result.append(('field', type_name + ('*' * len(stars)), member, bool(dims.strip())))
    return result


def parse(text: str, names: set[str]) -> dict[str, Struct]:
    """Named `typedef struct {...} Name;` definitions of `names` found in `text`."""
    clean = _strip(text)
    found = {}
    for match in re.finditer(r'typedef\s+struct\s*(?:\w+\s*)?\{', clean):
        start = match.end() - 1
        end = _matching(clean, start)
        tail = re.match(r'\s*([A-Za-z_]\w*)\s*;', clean[end + 1:])
        if tail and tail.group(1) in names:
            found[tail.group(1)] = Struct(tail.group(1), _body(tail.group(1), clean[start + 1:end]))
    return found


def _members(struct: Struct, known: dict[str, Struct], prefix: str, items: list | None = None,
             *, owner: str | None = None):
    """Yield ('directive', text) or ('scalar'|'struct', type, expression-of-member, member name, owner)."""
    owner = owner or struct.name
    for item in struct.items if items is None else items:
        if item[0] == 'directive':
            yield ('directive', item[1])
        elif item[0] == 'nested':
            yield from _members(struct, known, prefix + item[2] + '.', item[1], owner=owner)
        else:
            _, type_name, member, array = item
            if (owner, member) in SKIPPED:
                continue
            if type_name.endswith('*'):
                raise ConversionError(f'NES state layout: {owner}.{member} is a pointer; list it in SKIPPED or save an index')
            if type_name in known:
                yield ('struct', type_name, prefix + member, member, owner)
            elif type_name in FIXED_TYPES or (type_name == 'size_t' and not array):
                yield ('scalar', type_name, prefix + member, member, owner)
            else:
                raise ConversionError(f'NES state layout: {owner}.{member} has the type {type_name}, '
                                      'whose size or layout is not fixed')


def _functions(struct: Struct, known: dict[str, Struct]) -> str:
    name = struct.name
    save = [f'static uint8_t *rr_ser_{name}(uint8_t *b, const {name} *s) {{', '    (void)s;']
    load = [f'static const uint8_t *rr_de_{name}(const uint8_t *b, {name} *s) {{', '    (void)s;']
    size = [f'static size_t rr_size_{name}(void) {{', '    size_t n = 0;']
    for kind, *rest in _members(struct, known, ''):
        if kind == 'directive':
            for lines in (save, load, size):
                lines.append(rest[0])
            continue
        type_name, expression, member, owner = rest
        if kind == 'struct':
            each = f'sizeof(s->{expression}) / sizeof({type_name})'
            save.append(f'    for (size_t i = 0; i < {each}; i++) b = rr_ser_{type_name}(b, (const {type_name} *)&s->{expression} + i);')
            load.append(f'    for (size_t i = 0; i < {each}; i++) b = rr_de_{type_name}(b, ({type_name} *)&s->{expression} + i);')
            size.append(f'    n += rr_size_{type_name}() * (sizeof((({name} *)0)->{expression}) / sizeof({type_name}));')
        elif type_name == 'size_t':   # a file offset: always 8 bytes, whatever the host
            save.append(f'    {{ uint64_t v = (uint64_t)s->{expression}; memcpy(b, &v, 8); b += 8; }}')
            load.append(f'    {{ uint64_t v; memcpy(&v, b, 8); s->{expression} = (size_t)v; b += 8; }}')
            size.append('    n += 8;')
        elif type_name == 'bool':
            save.append(f'    memcpy(b, &s->{expression}, sizeof(s->{expression})); b += sizeof(s->{expression});')
            load.append(f'    {{ bool *out = (bool *)&s->{expression}; '
                        f'for (size_t i = 0; i < sizeof(s->{expression}); i++) out[i] = b[i] != 0; '
                        f'b += sizeof(s->{expression}); }}')
            size.append(f'    n += RR_STATE_FIELD({name}, {expression});')
        else:
            save.append(f'    memcpy(b, &s->{expression}, sizeof(s->{expression})); b += sizeof(s->{expression});')
            load.append(f'    memcpy(&s->{expression}, b, sizeof(s->{expression})); b += sizeof(s->{expression});')
            size.append(f'    n += RR_STATE_FIELD({name}, {expression});')
    save += ['    return b;', '}']
    load += ['    return b;', '}']
    size += ['    return n;', '}']
    return '\n'.join(save + load + size) + '\n'


def _order(roots: list[str], known: dict[str, Struct]) -> list[str]:
    """The roots and everything they contain, contained types first."""
    ordered: list[str] = []

    def visit(name: str, stack: tuple) -> None:
        if name in ordered:
            return
        if name in stack:
            raise ConversionError(f'NES state layout: {name} contains itself')
        struct = known[name]
        for kind, *rest in _members(struct, known, ''):
            if kind == 'struct':
                visit(rest[0], stack + (name,))
        ordered.append(name)

    for root in roots:
        visit(root, ())
    return ordered


def generate(known: dict[str, Struct], roots: list[str], *, preamble: bool = True) -> str:
    """C source with the writer, reader and size of each root and of the structs it contains."""
    missing = [root for root in roots if root not in known]
    if missing:
        raise ConversionError('NES state layout: not found in the sources: ' + ', '.join(missing))
    text = PREAMBLE if preamble else ''
    for name in _order(roots, known):
        text += '\n' + _functions(known[name], known)
    return text
